import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import * as OpenCC from 'opencc-js'
import zhCN from '../src/i18n/locales/zh-CN.ts'
import { chineseOverrides } from '../src/i18n/chinese-overrides.ts'

type ChineseLocale = keyof typeof chineseOverrides
type Catalog = Record<keyof typeof zhCN, string>
const profiles: Record<ChineseLocale, 'twp' | 'hk' | null> = {
  'zh-TW': 'twp', 'zh-HK': 'hk', 'zh-MO': 'hk', 'zh-SG': null, 'zh-MY': null,
}

export function convertMessage(text: string, convert: (text: string) => string) {
  // Placeholders, inline code and URLs are data, not translated prose.
  return text.split(/(\{[^{}]*\}|`[^`]*`|https?:\/\/[^\s<>"'`]+)/gu)
    .map((part, index) => index % 2 ? part : convert(part)).join('')
}

export function generateChineseCatalogs() {
  return Object.fromEntries(Object.entries(profiles).map(([locale, profile]) => {
    const convert = profile ? OpenCC.Converter({ from: 'cn', to: profile }) : (text: string) => text
    const catalog = Object.fromEntries(Object.entries(zhCN).map(([key, text]) => [key, convertMessage(text, convert)]))
    return [locale, { ...catalog, ...chineseOverrides[locale as ChineseLocale] }]
  })) as Record<ChineseLocale, Catalog>
}

if (import.meta.main) {
  const check = process.argv.includes('--check')
  const stale: string[] = []
  for (const [locale, catalog] of Object.entries(generateChineseCatalogs())) {
    const file = new URL(`../src/i18n/locales/${locale}.ts`, import.meta.url)
    const content = '// Generated by npm run generate:i18n. Edit zh-CN.ts or ../chinese-overrides.ts.\n'
      + "import type en from './en.ts'\n\nexport default " + JSON.stringify(catalog, null, 2)
      + ' satisfies Record<keyof typeof en, string>\n'
    if (existsSync(file) && readFileSync(file, 'utf8') === content) continue
    if (check) stale.push(locale)
    else writeFileSync(file, content)
  }
  if (stale.length) {
    console.error(`Chinese catalogs need regeneration: ${stale.join(', ')}. Run npm run generate:i18n.`)
    process.exitCode = 1
  } else console.log(`i18n: Chinese regional catalogs ${check ? 'verified' : 'generated'}.`)
}
