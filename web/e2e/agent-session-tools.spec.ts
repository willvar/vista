import { test, expect } from './fixtures'

test.use({ sessionActionTool: true })

test('agent session actions recover the exact preview and only mutate confirmed targets', { tag: '@responsive' }, async ({ vista, page }) => {
  const create = (title: string) => vista.api('/sessions', { method: 'POST', body: JSON.stringify({ title }) })
  const source = await create('Organize sessions')
  const idle = await create('Close this one')
  const changed = await create('Changed elsewhere')
  const keep = await create('Deselect this one')
  const open = (id: string) => vista.api(`/sessions/${id}/checkpoint`).then(state => state.session.open)
  const ask = (content: string) => vista.api(`/sessions/${source.id}/messages`, { method: 'POST', body: JSON.stringify({ content }) })

  await page.goto(`${vista.origin}/sessions/${source.id}`)
  await ask(`Close sessions: ${idle.id},${changed.id},${keep.id}`)
  const close = page.getByRole('dialog', { name: /^Close [23] sessions\?$/ })
  await expect(close).toBeVisible()
  expect(await open(idle.id)).toBe(true)
  await page.reload()
  await expect(close).toBeVisible()
  await expect(close.getByText('Only idle conversations will be closed. Their history is kept.')).toBeVisible()
  await vista.api(`/sessions/${changed.id}`, { method: 'PATCH', body: JSON.stringify({ title: 'Changed after preview' }) })
  await close.getByRole('checkbox', { name: 'Deselect this one' }).uncheck()
  await close.getByRole('button', { name: 'Close selected' }).click()
  await expect(page.getByText(/Session action result:.*changed_since_preview.*not_confirmed/)).toBeVisible()
  expect(await open(idle.id)).toBe(false)
  expect(await open(changed.id)).toBe(true)
  expect(await open(keep.id)).toBe(true)

  await ask(`Delete sessions: ${idle.id},${keep.id}`)
  const del = page.getByRole('dialog', { name: 'Delete session?' })
  await expect(del).toBeVisible()
  await expect(del.getByText(/cannot be restored in Vista/)).toBeVisible()
  await expect(del.getByRole('checkbox')).toHaveCount(1)
  await del.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByText(/Session action result:.*not_confirmed.*must_be_closed/)).toBeVisible()
  expect(await open(idle.id)).toBe(false)

  await ask(`Delete sessions: ${idle.id}`)
  await expect(del).toBeVisible()
  await del.getByRole('button', { name: 'Delete selected' }).click()
  await expect(page.getByText(/Session action result:.*"status":"deleted"/)).toBeVisible()
  expect((await page.request.get(`${vista.origin}/api/sessions/${idle.id}/checkpoint`)).status()).toBe(404)
  expect(await open(source.id)).toBe(true)
})
