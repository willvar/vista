import { closeSettings } from './settings-navigation'
import { test, expect } from './fixtures'

test('appearance follows the system, persists an override, and leaves the conversation draft intact', async ({ page, vista }, testInfo) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.goto(vista.origin + '/settings/general')
  const choices = page.locator('.appearance-options')
  await expect(choices.getByRole('button', { name: 'System', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await choices.getByRole('button', { name: 'Light', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(choices.getByRole('button', { name: 'Light', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('settings-light.png') })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await choices.getByRole('button', { name: 'Dark', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('settings-dark.png') })
  await choices.getByRole('button', { name: 'System', exact: true }).click()
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await closeSettings(page)
  await page.locator('.sender-card textarea').fill('Keep this draft when switching themes.')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('.sender-card textarea')).toHaveValue('Keep this draft when switching themes.')
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('workspace-dark.png') })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('workspace-light.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(testInfo.project.use.viewport!.width + 2)
})

test('appearance updates in another open tab without reloading it', async ({ page, context, vista }) => {
  const other = await context.newPage()
  await other.goto(vista.origin)
  await page.goto(vista.origin + '/settings/general')
  await page.locator('.appearance-options').getByRole('button', { name: 'Dark', exact: true }).click()
  await expect(other.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.locator('.appearance-options').getByRole('button', { name: 'Light', exact: true }).click()
  await expect(other.locator('html')).toHaveAttribute('data-theme', 'light')
  await other.close()
})

test.describe('appearance during execution', () => {
  test.use({ progressCalls: 1 })

  test('changing theme preserves streaming text, completion and execution details', async ({ page, vista }, testInfo) => {
    await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
    await page.reload()
    const release = vista.pauseModelReplies(true)
    try {
      const input = page.locator('.sender-card textarea')
      await input.fill('Inspect the current implementation')
      await input.press('Enter')
      await expect(page.locator('.main-output')).toContainText('Progress 1.')
      await page.emulateMedia({ colorScheme: 'dark' })
      await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
      await expect(page.locator('.main-output')).toContainText('Progress 1.')
      await expect(page.getByRole('button', { name: 'Stop current execution', exact: true })).toBeEnabled()
      await page.screenshot({ path: testInfo.outputPath('streaming-dark.png'), animations: 'disabled' })
      release()
      const reply = page.locator('article.assistant:not(.main-output)')
      await expect(reply).toHaveCount(1)
      await expect(reply).toContainText('Final progress answer.')
      await page.locator('.trace-overview-heading').click()
      await expect(page.locator('.run-trace .trace-reasoning')).toHaveCount(2)
      await expect(page.locator('.run-trace .trace-reasoning').first()).toHaveText('Private progress reasoning.')
      await expect(page.locator('.trace-reasoning button')).toHaveCount(0)
      await page.screenshot({ path: testInfo.outputPath('conversation-dark.png'), animations: 'disabled' })
      await page.reload()
      await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
      await expect(page.locator('.main-output')).toHaveCount(1)
      await expect(reply).toHaveCount(1)
      await expect(reply).toContainText('Final progress answer.')
    } finally { release() }
  })
})
