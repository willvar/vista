test('touch slider follows a finger and releases its drag state', { tag: '@responsive' }, async ({ page, isMobile }) => {
  test.skip(!isMobile, 'Touch behavior is exercised in the touch-enabled projects')
  const section = page.getByTestId('slider')
  await section.scrollIntoViewIfNeeded()
  const track = (await section.locator('.ui-slider-control').first().boundingBox())!
  const root = section.locator('.ui-slider').first()
  const client = await page.context().newCDPSession(page)
  const point = (fraction: number) => ({ x: track.x + track.width * fraction, y: track.y + track.height / 2 })
  try {
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point(.25)] })
    await expect(root).toHaveAttribute('data-dragging')
    for (const fraction of [.4, .6, .8, .95]) {
      await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [point(fraction)] })
      // Deliver a finger gesture across browser frames rather than collapsing
      // the movement into one synthetic tap.
      await page.waitForTimeout(25)
    }
    await expect(root).toHaveClass(/ui-slider-moving/)
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(page.getByRole('slider', { name: 'Level', exact: true })).toHaveAttribute('aria-valuenow', '4')
    await expect(root).not.toHaveAttribute('data-dragging')
    await expect(root).not.toHaveClass(/ui-slider-moving/)
  } finally { await client.detach() }
})
