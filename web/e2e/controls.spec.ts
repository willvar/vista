import { test as base, expect } from '@playwright/test'
import { controlAssets, startFrontend } from './frontend-server'

// Exercise the production wrappers directly, including states that are hard to
// hold while a real server acknowledges a write. No product route is added.
const test = base.extend<{}, { controlsOrigin: string }>({
  controlsOrigin: [async ({}, use) => {
    const server = await startFrontend({ directory: controlAssets })
    try { await use(server.origin) } finally { await server.close() }
  }, { scope: 'worker' }],
})

test.beforeEach(async ({ page, controlsOrigin }) => {
  await page.addInitScript(() => localStorage.setItem('vista-language', 'en'))
  await page.goto(controlsOrigin)
  await expect(page.getByRole('heading', { name: 'Buttons', exact: true })).toBeVisible()
})

test('buttons preserve native form behavior and disabled/loading actions cannot fire', { tag: '@responsive' }, async ({ page }) => {
  const section = page.getByTestId('buttons')
  await section.getByRole('button', { name: 'Ordinary', exact: true }).click()
  await expect(page.getByTestId('clicks')).toHaveText('1')
  await expect(page.getByTestId('submits')).toHaveText('0')
  await section.getByRole('button', { name: 'Submit', exact: true }).press('Enter')
  await expect(page.getByTestId('submits')).toHaveText('1')
  for (const name of ['Disabled', 'Loading']) {
    const button = section.getByRole('button', { name, exact: true })
    await expect(button).toBeDisabled()
    await button.click({ force: true })
  }
  for (const name of ['Disabled link', 'Loading link']) {
    const link = section.locator('a').filter({ hasText: name })
    await expect(link).toHaveAttribute('aria-disabled', 'true')
    await expect(link).not.toHaveAttribute('href')
    await link.click({ force: true })
  }
  await expect(page.getByTestId('clicks')).toHaveText('1')
  await expect(page.getByTestId('submits')).toHaveText('1')
  const ordinary = section.getByRole('button', { name: 'Ordinary', exact: true })
  const disabled = section.getByRole('button', { name: 'Disabled', exact: true })
  expect(await ordinary.evaluate(element => element.getBoundingClientRect().height)).toBe(36)
  const nativeDisabled = await disabled.evaluate(element => ({ color: getComputedStyle(element).color, background: getComputedStyle(element).backgroundColor }))
  await section.locator('a').filter({ hasText: 'Disabled link' }).hover()
  await expect.poll(() => section.locator('a').filter({ hasText: 'Disabled link' }).evaluate(element => ({ color: getComputedStyle(element).color, background: getComputedStyle(element).backgroundColor }))).toEqual(nativeDisabled)
  await section.getByRole('link', { name: 'Link', exact: true }).click()
  await expect(page).toHaveURL(/#destination$/)
  await expect(page.getByTestId('clicks')).toHaveText('2')
})

