test('sliders enforce bounds and reject disabled or unrelated drags', async ({ page }) => {
  const section = page.getByTestId('slider')
  const slider = page.getByRole('slider', { name: 'Level', exact: true })
  // Scrolling dismisses tooltips. Settle it before checking keyboard focus.
  await section.scrollIntoViewIfNeeded()
  await page.getByTestId('drag-origin').evaluate(element => element.focus({ preventScroll: true }))
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  await page.keyboard.press('Tab')
  await expect(slider).toBeFocused()
  await slider.press('End')
  await expect(slider).toHaveAttribute('aria-valuenow', '4')
  await expect(page.getByRole('tooltip')).toHaveText('Level 4')
  await slider.press('ArrowRight')
  await expect(slider).toHaveAttribute('aria-valuenow', '4')
  await slider.press('Home')
  await expect(slider).toHaveAttribute('aria-valuenow', '0')
  await expect(page.getByRole('tooltip')).toHaveText('Level 0')
  await slider.press('ArrowRight')
  await expect(slider).toHaveAttribute('aria-valuenow', '1')
  const disabled = page.getByRole('slider', { name: 'Disabled level', exact: true })
  const disabledRoot = disabled.locator('xpath=ancestor::*[@data-scope="slider" and @data-part="root"]')
  await disabled.click({ force: true })
  await expect(disabled).toHaveAttribute('aria-valuenow', '2')
  await expect(disabledRoot).not.toHaveClass(/ui-slider-moving/)
  await section.scrollIntoViewIfNeeded()
  const track = (await section.locator('.ui-slider-control').first().boundingBox())!
  const root = section.locator('.ui-slider').first()
  await page.mouse.move(track.x + track.width * .75, track.y + track.height / 2)
  await page.mouse.down()
  await expect(root).toHaveAttribute('data-dragging')
  await page.mouse.move(track.x + track.width, track.y + track.height / 2)
  await expect(root).toHaveClass(/ui-slider-moving/)
  await page.mouse.up()
  await expect(root).not.toHaveAttribute('data-dragging')
  await expect(root).not.toHaveClass(/ui-slider-moving/)
  await expect(slider).toHaveAttribute('aria-valuenow', '4')
  await slider.press('Home')
  await slider.press('ArrowRight')
  const origin = (await page.getByTestId('drag-origin').boundingBox())!
  await page.mouse.move(origin.x + 5, origin.y + 5)
  await page.mouse.down()
  await page.mouse.move(track.x + track.width / 2, track.y + track.height / 2)
  await page.mouse.up()
  await expect(slider).toHaveAttribute('aria-valuenow', '1')
  await expect(root).not.toHaveClass(/ui-slider-moving/)
  await expect(root).not.toHaveAttribute('data-dragging')
})

