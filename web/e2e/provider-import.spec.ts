import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { test, expect, type VistaFixture } from './fixtures'

function seedOpenCode(vista: VistaFixture, config: object) {
  const root = dirname(vista.workspacePath)
  const configPath = join(root, 'opencode', 'opencode.jsonc')
  mkdirSync(dirname(configPath), { recursive: true })
  writeFileSync(configPath, '// OpenCode configuration\n' + JSON.stringify(config), { mode: 0o600 })
  return { configPath, modelsPath: join(root, 'vista', 'models.json') }
}

test.describe('provider import', () => {
  test.use({ configuredProvider: false })

  test('previews OpenCode, keeps cancellation read-only and imports selected connections', async ({ page, vista }, testInfo) => {
    const paths = seedOpenCode(vista, { providers: {
      gateway: { name: 'OpenCode gateway', package: '@opencode/ai/providers/openai-compatible', settings: { baseURL: vista.modelEndpoint, apiKey: 'import-test-secret' } },
      unsupported: { name: 'Unsupported connection', package: 'unsupported-package' },
      deepseek: { settings: { apiKey: 'deepseek-test-secret' } },
    }, plugins: [{ package: './extensions/gateway', options: { apiKey: 'plugin-test-secret' } }] })
    const before = readFileSync(paths.modelsPath, 'utf8')
    let reads = 0
    page.on('request', request => { if (request.url().endsWith('/api/provider-import')) reads++ })
    await page.goto(vista.origin + '/settings/models')
    const settings = page.locator('.settings-page')
    const open = settings.getByRole('button', { name: 'Import connections', exact: true })
    const plus = settings.getByRole('button', { name: 'Connect provider', exact: true })
    await expect(open).toBeVisible()
    const importBounds = await open.boundingBox(), plusBounds = await plus.boundingBox()
    expect(importBounds!.x).toBeLessThan(plusBounds!.x)
    await open.click()
    const modal = page.locator('.provider-import-modal')
    await expect(modal).toBeVisible()
    await expect(modal.getByText('Importing before connecting any providers is recommended. Existing connections will be kept.')).toBeVisible()
    await expect(modal.locator('.provider-import-source .ant-select')).toContainText('OpenCode')
    await expect(modal.locator('.provider-import-source .ant-select')).not.toContainText('v2')
    await expect(modal.locator('.provider-import-list')).toHaveCount(0)
    expect(reads).toBe(0)
    await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
    await expect(modal.getByRole('checkbox', { name: /OpenCode gateway/ })).toBeChecked()
    await expect(modal.getByRole('checkbox', { name: /Unsupported connection/ })).toBeDisabled()
    await expect(modal.getByText('Requires an unsupported plugin or connection setting')).toBeVisible()
    await expect(modal.locator('.provider-import-hint').filter({ hasText: 'Read connections and sign-in credentials' })).toContainText('For connections that were not detected, try asking the agent to help import them.')
    await expect(modal.locator('.ant-alert-warning')).toHaveCount(0)
    expect(await modal.textContent()).not.toContain('test-secret')
    expect(readFileSync(paths.modelsPath, 'utf8')).toBe(before)
    await page.keyboard.press('Escape')
    await expect(modal).toBeHidden()
    await expect(settings).toBeVisible()
    expect(readFileSync(paths.modelsPath, 'utf8')).toBe(before)

    await open.click()
    await expect(modal.locator('.provider-import-list')).toHaveCount(0)
    expect(reads).toBe(1)
    await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
    const deepseek = modal.getByRole('checkbox', { name: /DeepSeek/ })
    await expect(deepseek).toBeChecked()
    await deepseek.uncheck()
    await modal.getByRole('button', { name: 'Import (1)', exact: true }).click()
    await expect(modal).toBeHidden()
    await expect(settings.getByText('Imported 1 connections.', { exact: true })).toBeVisible()
    await expect(settings.locator('.configured-provider').filter({ hasText: 'OpenCode gateway' })).toBeVisible()
    const saved = JSON.parse(readFileSync(paths.modelsPath, 'utf8'))
    expect(saved.models).toHaveLength(1)
    expect(saved.models[0]).toMatchObject({ name: 'OpenCode gateway', provider: 'openai-chat', providerId: 'custom', apiKey: 'import-test-secret' })

    await open.click()
    await expect(modal.locator('.provider-import-list')).toHaveCount(0)
    expect(reads).toBe(3)
    await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
    await expect(modal.getByRole('checkbox', { name: /OpenCode gateway/ })).toBeDisabled()
    await expect(modal.getByText('Already connected to this provider and address')).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('provider-import.png'), animations: 'disabled' })
    await modal.getByRole('button', { name: 'Cancel', exact: true }).click()
  })

  test('source changes require a new preview and path errors are recoverable', async ({ page, vista }) => {
    const paths = seedOpenCode(vista, { providers: { deepseek: { settings: { apiKey: 'first-test-secret' } } } })
    await page.goto(vista.origin + '/settings/models')
    await page.getByRole('button', { name: 'Import connections', exact: true }).click()
    const modal = page.locator('.provider-import-modal')
    await expect(modal.locator('.provider-import-list')).toHaveCount(0)
    await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
    const confirm = modal.getByRole('button', { name: 'Import (1)', exact: true })
    await expect(confirm).toBeEnabled()
    writeFileSync(paths.configPath, JSON.stringify({ providers: { deepseek: { settings: { apiKey: 'second-test-secret' } } } }), { mode: 0o600 })
    await confirm.click()
    await expect(modal.locator('.ant-alert-error')).toContainText('OpenCode configuration changed')
    await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
    await expect(modal.locator('.ant-alert-error')).toHaveCount(0)
    await modal.getByText('File paths', { exact: true }).click()
    await modal.getByRole('textbox', { name: 'Configuration file', exact: true }).fill(join(dirname(paths.configPath), 'missing.json'))
    await expect(modal.locator('.provider-import-list')).toHaveCount(0)
    await expect(modal.getByRole('button', { name: /^Import \(0\)$/ })).toBeDisabled()
    await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
    await expect(modal.locator('.ant-alert-error')).toContainText('could not read OpenCode configuration')
    await modal.getByRole('textbox', { name: 'Configuration file', exact: true }).fill('')
    await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
    await expect(confirm).toBeEnabled()
    await confirm.click()
    await expect(modal).toBeHidden()
    const saved = JSON.parse(readFileSync(paths.modelsPath, 'utf8'))
    expect(saved.models[0].apiKey).toBe('second-test-secret')
  })

  test('mixed OpenCode formats offer one credential choice and import the selected source', async ({ page, vista }) => {
    const paths = seedOpenCode(vista, {
      provider: { gateway: { name: 'Obsolete gateway', npm: 'unsupported-plugin', options: { apiKey: '{file:missing}' } } },
      providers: { gateway: { name: 'Mixed gateway', package: '@opencode/ai/providers/openai-compatible', settings: { baseURL: vista.modelEndpoint } } },
    })
    const data = join(dirname(vista.workspacePath), 'data', 'opencode')
    mkdirSync(data, { recursive: true })
    const authPath = join(data, 'auth.json')
    const auth = JSON.stringify({ gateway: { type: 'api', key: 'legacy-test-secret' } })
    writeFileSync(authPath, auth, { mode: 0o600 })
    const db = new DatabaseSync(join(data, 'opencode.db'))
    db.exec('CREATE TABLE credential (id TEXT PRIMARY KEY, integration_id TEXT, value TEXT, active INTEGER, time_created INTEGER)')
    db.prepare('INSERT INTO credential VALUES (?, ?, ?, 1, 1)').run('key', 'gateway', JSON.stringify({ type: 'key', key: 'current-test-secret' }))
    db.close()

    await page.goto(vista.origin + '/settings/models')
    await page.getByRole('button', { name: 'Import connections', exact: true }).click()
    const modal = page.locator('.provider-import-modal')
    await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
    await expect(modal.getByText('Different credentials were found for the same connection. Choose one source to import.')).toBeVisible()
    const legacy = modal.getByRole('checkbox', { name: /Mixed gateway.*auth.json/ })
    const current = modal.getByRole('checkbox', { name: /Mixed gateway.*opencode.db/ })
    await expect(legacy).not.toBeChecked()
    await expect(current).not.toBeChecked()
    await expect(modal.getByRole('button', { name: 'Import (0)', exact: true })).toBeDisabled()
    await legacy.check()
    await current.check()
    await expect(legacy).not.toBeChecked()
    await expect(current).toBeChecked()
    await legacy.check()
    await expect(current).not.toBeChecked()
    expect(await modal.textContent()).not.toContain('test-secret')
    await modal.getByRole('button', { name: 'Import (1)', exact: true }).click()
    await expect(modal).toBeHidden()
    const saved = JSON.parse(readFileSync(paths.modelsPath, 'utf8'))
    expect(saved.models).toHaveLength(1)
    expect(saved.models[0]).toMatchObject({ name: 'Mixed gateway', provider: 'openai-chat', apiKey: 'legacy-test-secret' })
    expect(readFileSync(authPath, 'utf8')).toBe(auth)
  })
})
