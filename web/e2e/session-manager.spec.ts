test('manager titles save inline on blur and Enter while drafts survive remote reordering', async ({ page, vista }) => {
  const item = await vista.api('/sessions', { method: 'POST', body: JSON.stringify({ title: 'Original title' }) })
  const other = await vista.api('/sessions', { method: 'POST', body: JSON.stringify({ title: 'Another task' }) })
  await page.goto(vista.origin + '/sessions')
  const manager = page.locator('.session-manager-page')
  const row = manager.locator(`[data-session-id="${item.id}"]`)
  const changes: object[] = []
  page.on('request', request => {
    if (request.method() === 'PATCH' && new URL(request.url()).pathname === `/api/sessions/${item.id}`) changes.push(request.postDataJSON())
  })
  await sessionManagerAction(page, row, 'Rename')
  const input = row.getByRole('textbox', { name: 'Session title', exact: true })
  await expect(input).toBeFocused()
  await input.fill('Draft kept across updates')
  await vista.api(`/sessions/${other.id}`, { method: 'PATCH', body: JSON.stringify({ pinned: true }) })
  await vista.api(`/sessions/${item.id}`, { method: 'PATCH', body: JSON.stringify({ title: 'Remote title' }) })
  await expect(input).toBeFocused()
  await expect(input).toHaveValue('Draft kept across updates')
  await manager.locator('h2').click()
  await expect(row.locator('.session-name')).toHaveText('Draft kept across updates')
  await sessionManagerAction(page, row, 'Rename')
  await input.fill('Saved with Enter')
  await input.press('Enter')
  await expect(row.locator('.session-name')).toHaveText('Saved with Enter')
  await sessionManagerAction(page, row, 'Rename')
  await input.fill('Discard this draft')
  await input.press('Escape')
  await expect(row.locator('.session-name')).toHaveText('Saved with Enter')
  await expect(manager).toBeVisible()
  expect(changes).toEqual([{ title: 'Draft kept across updates' }, { title: 'Saved with Enter' }])
  await sessionManagerAction(page, row, 'Delete')
  const confirmation = page.getByRole('dialog', { name: 'Delete session?', exact: true })
  await expect(confirmation).toContainText('Saved with Enter')
  expect((await vista.api('/sessions')).some((session: { id: string }) => session.id === item.id)).toBe(true)
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await expect(manager).toBeVisible()
  const longTitle = 'W'.repeat(200)
  await vista.api(`/sessions/${item.id}`, { method: 'PATCH', body: JSON.stringify({ title: longTitle }) })
  await expect(row.locator('.session-name')).toHaveText(longTitle)
  await sessionManagerAction(page, row, 'Delete')
  await expect(confirmation).toContainText(longTitle)
  expect(await confirmation.evaluate(element => element.scrollWidth - element.clientWidth), 'An unbroken title must wrap inside the confirmation').toBeLessThanOrEqual(1)
  await page.keyboard.press('Escape')
  await expect(confirmation).toBeHidden()
  await expect(manager).toBeVisible()
})

