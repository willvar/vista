import type { Locator, Page } from '@playwright/test'
import { test, expect } from './fixtures'

async function chooseSize(page: Page, pager: Locator, size: number) {
  await pager.getByRole('combobox', { name: 'Per page', exact: true }).click()
  await page.locator('.ui-select-dropdown:visible .ui-select-item-option-content').filter({ hasText: new RegExp(`^${size}$`) }).click()
}

test('session management pages archived summaries, searches all records and limits bulk selection to the current page', async ({ page, vista }, info) => {
  test.setTimeout(60_000)
  await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
  for (let i = 0; i < 21; i++) {
    const item = await vista.api('/sessions', { method: 'POST', body: JSON.stringify({ title: `Archive ${String(i).padStart(2, '0')}` }) })
    await vista.api(`/sessions/${item.id}/close`, { method: 'POST' })
  }
  // Creation timestamps have second precision; IDs break ties. Use the
  // authoritative order instead of assuming insertion order within a second.
  const ordered = (await vista.api('/sessions?page=1&pageSize=100&open=false')).items
  const oldestID = ordered.at(-1).id
  const penultimateID = ordered.at(-2).id
  await vista.api(`/sessions/${oldestID}`, { method: 'PATCH', body: JSON.stringify({ title: 'Oldest searchable archive' }) })
  const pages: URL[] = []
  page.on('request', request => {
    const url = new URL(request.url())
    if (request.method() === 'GET' && url.pathname === '/api/sessions' && url.searchParams.has('page')) pages.push(url)
  })
  await page.goto(vista.origin + '/')
  await expect(page.locator('.sender-card textarea')).toBeVisible()
  expect(pages).toHaveLength(0)
  await page.goto(vista.origin + '/sessions')
  const manager = page.locator('.session-manager-page')
  const rows = manager.locator('.managed-session')
  const pager = manager.locator('.list-pagination')
  const range = pager.getByRole('status')
  await expect(rows).toHaveCount(10)
  await expect(range).toHaveText('1–10 of 21')
  await expect(pager.getByRole('combobox', { name: 'Per page' })).toBeInViewport()
  await manager.getByRole('checkbox', { name: 'Select all shown', exact: true }).check()
  await expect(manager.locator('.session-bulk-actions [role="status"]')).toHaveText('10 selected')
  await pager.locator('.ui-pagination-item-2').click()
  await expect(range).toHaveText('11–20 of 21')
  await expect(manager.locator('.session-bulk-actions [role="status"]')).toHaveText('0 selected')
  await chooseSize(page, pager, 20)
  await expect(rows).toHaveCount(20)
  await expect(range).toHaveText('1–20 of 21')
  await chooseSize(page, pager, 100)
  await expect(rows).toHaveCount(21)
  await expect(range).toHaveText('1–21 of 21')
  await chooseSize(page, pager, 10)
  await expect(rows).toHaveCount(10)
  const search = manager.getByRole('textbox', { name: 'Search sessions', exact: true })
  await search.fill('Oldest searchable')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('Oldest searchable archive')
  await expect(range).toHaveText('1–1 of 1')
  const filter = manager.locator('.session-manager-controls .ui-select')
  await filter.click()
  await page.locator('.ui-select-dropdown:visible .ui-select-item-option-content').filter({ hasText: /^Open sessions$/ }).click()
  await expect(rows).toHaveCount(0)
  await expect(pager).toBeHidden()
  await filter.click()
  await page.locator('.ui-select-dropdown:visible .ui-select-item-option-content').filter({ hasText: /^Closed sessions$/ }).click()
  await expect(rows).toHaveCount(1)
  await search.fill('')
  await expect(rows).toHaveCount(10)
  await pager.locator('.ui-pagination-item-3').click()
  await expect(rows).toHaveCount(1)
  await expect(range).toHaveText('21–21 of 21')
  await manager.getByRole('checkbox', { name: 'Select all shown', exact: true }).check()
  await manager.getByRole('button', { name: 'Delete selected', exact: true }).click()
  const confirmation = page.getByRole('dialog').filter({ hasText: 'Delete 1 selected sessions and their history?' })
  await confirmation.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(range).toHaveText('11–20 of 20')
  await expect(rows).toHaveCount(10)
  await expect(manager.locator('.session-bulk-actions [role="status"]')).toHaveText('0 selected')
  await vista.api(`/sessions/${penultimateID}`, { method: 'PATCH', body: JSON.stringify({ title: 'Updated from another client' }) })
  const updated = rows.filter({ hasText: 'Updated from another client' })
  await expect(updated).toHaveCount(1)
  await updated.getByRole('button', { name: 'Rename', exact: true }).click()
  const editor = manager.getByRole('textbox', { name: 'Session title', exact: true })
  await editor.fill('Unsaved title draft')
  await vista.api(`/sessions/${penultimateID}`, { method: 'PATCH', body: JSON.stringify({ title: 'Title changed during editing' }) })
  await expect(editor).toHaveValue('Unsaved title draft')
  await expect(pager.getByRole('combobox', { name: 'Per page', exact: true })).toBeDisabled()
  await manager.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(rows.filter({ hasText: 'Title changed during editing' })).toHaveCount(1)
  await page.screenshot({ path: info.outputPath('session-pagination.png'), animations: 'disabled' })
  expect(pages.every(url => Number(url.searchParams.get('pageSize')) <= 100)).toBe(true)
  expect(pages.some(url => url.searchParams.get('search') === 'Oldest searchable')).toBe(true)
  const close = manager.getByRole('button', { name: 'Close session manager', exact: true })
  if (await close.isVisible()) await close.click()
  else await manager.getByRole('button', { name: 'Back to conversation', exact: true }).click()
  await expect(manager).toBeHidden()
  const settled = pages.length
  await vista.api(`/sessions/${penultimateID}`, { method: 'PATCH', body: JSON.stringify({ title: 'Changed after closing manager' }) })
  await page.waitForTimeout(300)
  expect(pages).toHaveLength(settled)
})

test('memory management pages entries, changes page size and returns to a valid page after deletion', async ({ page, vista }, info) => {
  for (let i = 0; i < 21; i++) await vista.api('/memories', { method: 'POST', body: JSON.stringify({ action: 'add', text: `Preference ${String(i).padStart(2, '0')}` }) })
  await page.goto(vista.origin + '/settings/personalization')
  await page.getByRole('button', { name: 'Manage memories', exact: true }).click()
  const manager = page.getByRole('dialog', { name: /^Manage memories/ })
  const previews = manager.locator('.memory-text')
  const pager = manager.locator('.list-pagination')
  const range = pager.getByRole('status')
  await expect(previews).toHaveCount(10)
  await expect(range).toHaveText('1–10 of 21')
  await expect(pager.getByRole('combobox', { name: 'Per page' })).toBeInViewport()
  await pager.locator('.ui-pagination-item-2').click()
  await expect(previews.first()).toHaveText('Preference 10')
  await expect(range).toHaveText('11–20 of 21')
  await chooseSize(page, pager, 20)
  await expect(previews).toHaveCount(20)
  await expect(range).toHaveText('1–20 of 21')
  await chooseSize(page, pager, 50)
  await expect(previews).toHaveCount(21)
  await chooseSize(page, pager, 10)
  await expect(previews).toHaveCount(10)
  await pager.locator('.ui-pagination-item-3').click()
  await expect(previews).toHaveText('Preference 20')
  await manager.getByRole('button', { name: 'Delete memory: Preference 20', exact: true }).click()
  await page.locator('.memory-delete-popover').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(range).toHaveText('11–20 of 20')
  await expect(previews).toHaveCount(10)
  await expect(manager.locator('.memory-count')).toHaveText('20')
  await page.screenshot({ path: info.outputPath('memory-pagination.png'), animations: 'disabled' })
  const overflow = await manager.evaluate(element => element.scrollWidth - element.clientWidth)
  expect(overflow).toBeLessThanOrEqual(2)
  await manager.getByRole('button', { name: 'Add memory', exact: true }).click()
  await manager.getByRole('textbox', { name: 'Preference', exact: true }).fill('The newly added preference.')
  let reads = 0
  page.on('request', request => { if (request.method() === 'GET' && new URL(request.url()).pathname === '/api/memories') reads++ })
  await manager.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(previews).toHaveText('The newly added preference.')
  await expect(range).toHaveText('21–21 of 21')
  await page.waitForTimeout(300)
  expect(reads).toBe(0)
  await expect(page.locator('.state-sync-error')).toHaveCount(0)
})
