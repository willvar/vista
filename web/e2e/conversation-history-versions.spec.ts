import { test, expect } from './fixtures'

test.use({ replyWithPrompt: true })

test('branching defaults off and same-session edits can be recovered', { tag: '@responsive' }, async ({ page, vista, isMobile }) => {
  test.setTimeout(65_000)
  await page.goto(`${vista.origin}/settings/personalization`)
  await expect(page.locator('.personalization-settings-content > :last-child')).toHaveAccessibleName('Branching')
  const toggle = page.getByRole('switch', { name: 'Branching', exact: true })
  await expect(toggle).not.toBeChecked()
  const figure = page.locator('.branching-figure')
  await expect(figure).toBeVisible()
  await expect(figure).toContainText('The earlier version can be restored.')
  await expect(figure).toContainText('Create a separate branch.')
  await expect(figure.locator('figcaption')).toHaveText('You can still switch between existing branches when branching is off.')
  expect(await figure.evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
  await toggle.click()
  await expect(toggle).toBeChecked()
  await page.reload()
  await expect(toggle).toBeChecked()
  await toggle.click()
  await expect(toggle).not.toBeChecked()
  expect((await vista.api('/preferences')).branching).toBe(false)

  const post = (path: string, body: object) => vista.api(path, { method: 'POST', body: JSON.stringify(body) })
  const session = await post('/sessions', { title: 'Recoverable timeline' })
  const path = `/sessions/${session.id}`
  const idle = () => expect.poll(async () => (await vista.api(`${path}/checkpoint`)).session.executing).toBe(false)
  await post(`${path}/messages`, { content: 'Original message' })
  await idle()
  await page.goto(vista.origin + path)
  const original = page.locator('article.user').filter({ hasText: 'Original message' })
  await expect(original).toBeVisible()
  const sender = page.locator('.sender-card textarea')
  await sender.fill('Unsent continuation')
  if (!isMobile) await original.hover()
  await original.getByRole('button', { name: 'Edit message', exact: true }).click()
  await expect(sender).toHaveValue('Original message')
  await sender.fill('Changed message')
  const resent = page.waitForResponse(reply => reply.url().endsWith(`${path}/messages`) && reply.request().method() === 'POST')
  await page.locator('.sender-card .composer-send').click()
  const reply = await resent
  expect(reply.status(), reply.ok() ? 'replacement send accepted' : await reply.text()).toBe(202)
  await expect(page.locator('article.user')).toContainText('Changed message')
  await expect(original).toHaveCount(0)
  await expect(sender).toHaveValue('Unsent continuation')
  await idle()
  expect(await vista.api(`${path}/branches`)).toHaveLength(1)
  await expect(page).toHaveURL(vista.origin + path)

  const restoreName = { name: 'Restore earlier version', exact: true }
  await expect(page.getByRole('button', restoreName)).toBeVisible()
  await expect(page.locator('.conversation-header-tools').getByRole('button', restoreName), 'history recovery stays out of the header').toHaveCount(0)
  const restoreAction = page.locator('.conversation-revision-actions').getByRole('button', restoreName)
  await restoreAction.click()
  const dialog = page.getByRole('dialog', { name: 'Restore earlier version', exact: true })
  await dialog.getByRole('button', { name: 'preview', exact: true }).first().click()
  await expect(dialog).toContainText('Original message')
  const restored = page.waitForResponse(reply => /\/history-versions\/\d+$/.test(reply.url()) && reply.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Restore earlier version', exact: true }).click()
  expect((await restored).status()).toBe(204)
  await expect(dialog).toHaveCount(0)
  const point = await vista.api(`${path}/snapshot`)
  expect(point.messages.filter((message: { role: string }) => message.role === 'user').map((message: { content: string }) => message.content)).toEqual(['Original message'])
  await expect(original).toBeVisible()
  await expect(page).toHaveURL(vista.origin + path)
  await page.reload()
  await expect(original).toBeVisible()
  expect((await vista.api(`${path}/history-versions`)).items).toHaveLength(2)
  if (!isMobile) await original.hover()
  await original.getByRole('button', { name: 'Withdraw message', exact: true }).click()
  const withdraw = page.getByRole('dialog', { name: 'Withdraw this message?', exact: true })
  await expect(withdraw).toContainText('previous history can be restored')
  await withdraw.getByRole('button', { name: 'Withdraw message', exact: true }).click()
  await expect(sender).toHaveValue('Original message')
  await expect(original).toHaveCount(0)
  await expect(restoreAction).toBeVisible()
  await expect(page).toHaveURL(vista.origin + path)
  expect(await vista.api(`${path}/branches`)).toHaveLength(1)
})


test('a change in another tab cannot turn a confirmed withdrawal into a fork', async ({ page, vista }) => {
  const session = await vista.api('/sessions', { method: 'POST', body: JSON.stringify({ title: 'Stale withdrawal mode' }) })
  const path = `/sessions/${session.id}`
  await vista.api(`${path}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Keep this history' }) })
  await expect.poll(async () => (await vista.api(`${path}/checkpoint`)).session.executing).toBe(false)
  await page.goto(vista.origin + path)
  const original = page.locator('article.user').filter({ hasText: 'Keep this history' })
  await original.hover()
  await original.getByRole('button', { name: 'Withdraw message', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: 'Withdraw this message?', exact: true })
  await expect(confirmation).toContainText('previous history can be restored')
  const settings = await page.context().newPage()
  try {
    await settings.goto(`${vista.origin}/settings/personalization`)
    const toggle = settings.getByRole('switch', { name: 'Branching', exact: true })
    await expect(toggle).not.toBeChecked()
    await toggle.click()
    await expect(toggle).toBeChecked()
    const response = page.waitForResponse(reply => reply.url().endsWith('/revert') && reply.request().method() === 'POST')
    await confirmation.getByRole('button', { name: 'Withdraw message', exact: true }).click()
    expect((await response).status()).toBe(409)
    await expect(original).toBeVisible()
    expect(await vista.api(`${path}/branches`)).toHaveLength(1)
    expect((await vista.api(`${path}/history-versions`)).items).toHaveLength(0)
  } finally { await settings.close() }
})
