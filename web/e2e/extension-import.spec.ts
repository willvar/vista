import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { test, expect, type VistaFixture } from './fixtures'

function seedOpenCode(vista: VistaFixture, config: object) {
  const root = join(dirname(vista.workspacePath), 'opencode')
  mkdirSync(root, { recursive: true })
  writeFileSync(join(root, 'opencode.jsonc'), '// OpenCode configuration\n' + JSON.stringify(config), { mode: 0o600 })
  return root
}

test('MCP import reads only on request and saves without starting commands', async ({ page, vista }, testInfo) => {
  const marker = join(vista.workspacePath, 'must-not-run')
  seedOpenCode(vista, { mcp: { servers: {
    imported: { type: 'local', command: [process.execPath, '-e', `require('node:fs').writeFileSync(${JSON.stringify(marker)}, 'ran')`], cwd: vista.workspacePath },
    unsupported: { type: 'local', command: [process.execPath], environment: { KEY: 'source-secret' } },
  } } })
  let reads = 0
  page.on('request', request => { if (request.url().endsWith('/api/extension-import')) reads++ })
  await page.goto(`${vista.origin}/settings/mcp`)
  const open = page.getByRole('button', { name: 'Import MCP services', exact: true })
  await open.click()
  const modal = page.locator('.provider-import-modal')
  await expect(modal).toBeVisible()
  expect(reads).toBe(0)
  await expect(modal.locator('.provider-import-list')).toHaveCount(0)
  await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
  await expect(modal.getByRole('checkbox', { name: /^imported/ })).toBeChecked()
  await expect(modal.getByRole('checkbox', { name: /^unsupported/ })).toBeDisabled()
  expect(await modal.textContent()).not.toContain('source-secret')
  expect((await vista.api('/mcp-config')).servers).toEqual([])
  expect(existsSync(marker)).toBe(false)
  await modal.getByRole('button', { name: 'Cancel', exact: true }).click()
  await open.click()
  await expect(modal.locator('.provider-import-list')).toHaveCount(0)
  expect(reads).toBe(1)
  await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
  await modal.getByRole('button', { name: 'Import (1)', exact: true }).click()
  await expect(modal).toBeHidden()
  await expect(page.locator('[data-mcp="imported"]')).toBeVisible()
  expect((await vista.api('/mcp-config')).servers[0]).toMatchObject({ name: 'imported', transport: 'stdio', command: process.execPath, directory: vista.workspacePath })
  expect(existsSync(marker)).toBe(false)
  await open.click()
  await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
  await expect(modal.getByRole('checkbox', { name: /^imported/ })).toBeDisabled()
  await expect(modal.getByText('An item with this name already exists')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('mcp-import.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(modal).toBeHidden()
  await expect(page).toHaveURL(/\/settings\/mcp$/)
})

test('legacy OpenCode MCP entries retain custom headers through import and editing', async ({ page, vista }) => {
  seedOpenCode(vista, { provider: {}, mcp: {
    context7: { type: 'remote', url: 'https://example.invalid/mcp', headers: { CONTEXT7_API_KEY: 'source-secret' }, enabled: true },
  } })
  const configPath = join(dirname(vista.workspacePath), 'vista', 'mcp.json')
  const savedServers = () => JSON.parse(readFileSync(configPath, 'utf8'))
  await page.goto(`${vista.origin}/settings/mcp`)
  await page.getByRole('button', { name: 'Import MCP services', exact: true }).click()
  const modal = page.locator('.provider-import-modal')
  await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
  await expect(modal.getByRole('checkbox', { name: /^context7/ })).toBeChecked()
  expect(await modal.textContent()).not.toContain('source-secret')
  await modal.getByRole('button', { name: 'Import (1)', exact: true }).click()
  await expect(modal).toBeHidden()
  expect(savedServers()[0].headers).toEqual({ CONTEXT7_API_KEY: 'source-secret' })
  expect(savedServers()[0].token).toBeUndefined()
  const readback = await vista.api('/mcp-config')
  expect(JSON.stringify(readback)).not.toContain('source-secret')
  expect(readback.servers[0].headerNames).toEqual(['CONTEXT7_API_KEY'])

  await page.reload()
  await page.getByRole('button', { name: 'Edit context7', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Edit MCP server', exact: true })
  await expect(editor.getByLabel('Header name 1', { exact: true })).toHaveValue('CONTEXT7_API_KEY')
  const value = editor.getByLabel('Header value 1', { exact: true })
  await expect(value).toHaveValue('')
  await expect(value).toHaveAttribute('placeholder', 'Leave blank to keep saved value')
  await editor.getByLabel('Name', { exact: true }).fill('Renamed Context7')
  await editor.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(editor).toBeHidden()
  expect(savedServers()[0].headers).toEqual({ CONTEXT7_API_KEY: 'source-secret' })

  await page.getByRole('button', { name: 'Edit Renamed Context7', exact: true }).click()
  await editor.getByLabel('Header value 1', { exact: true }).fill('replacement-secret')
  await editor.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(editor).toBeHidden()
  expect(savedServers()[0].headers).toEqual({ CONTEXT7_API_KEY: 'replacement-secret' })

  await page.getByRole('button', { name: 'Edit Renamed Context7', exact: true }).click()
  await editor.getByRole('button', { name: 'Remove request header 1', exact: true }).click()
  await editor.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(editor).toBeHidden()
  expect(savedServers()[0].headers).toBeUndefined()
})

test('legacy configured skill paths are recognized without version selection', async ({ page, vista }) => {
  const root = seedOpenCode(vista, { provider: {}, skills: { paths: ['custom-skills'], urls: [] } })
  const source = join(vista.workspacePath, 'custom-skills', 'legacy-guide')
  mkdirSync(source, { recursive: true })
  const content = '---\nname: Legacy guide\ndescription: A guide from a configured path\n---\nInspect source evidence.'
  writeFileSync(join(source, 'SKILL.md'), content)
  await page.goto(vista.origin + '/settings/skills')
  await page.getByRole('button', { name: 'Import skills', exact: true }).click()
  const modal = page.locator('.provider-import-modal')
  await expect(modal.locator('.provider-import-source .ant-select')).toContainText('OpenCode')
  await modal.getByText('File paths', { exact: true }).click()
  await modal.getByRole('textbox', { name: 'Source working directory', exact: true }).fill(vista.workspacePath)
  await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
  await expect(modal.getByRole('checkbox', { name: /Legacy guide/ })).toBeChecked()
  await modal.getByRole('button', { name: 'Import (1)', exact: true }).click()
  await expect(modal).toBeHidden()
  const { directory } = await vista.api('/skills')
  expect(readFileSync(join(directory, 'legacy-guide', 'SKILL.md'), 'utf8')).toBe(content)
  expect(JSON.parse(readFileSync(join(root, 'opencode.jsonc'), 'utf8').split('\n').slice(1).join('\n'))).toHaveProperty('skills.paths')
})

test('skill import copies supporting files, keeps existing skills and rejects stale previews', async ({ page, vista }, testInfo) => {
  const root = seedOpenCode(vista, {})
  const source = join(root, 'skills', 'review-pack')
  mkdirSync(join(source, 'assets'), { recursive: true })
  mkdirSync(join(source, 'references'))
  const instructions = '---\nname: Imported review\ndescription: Review changes using the included references\n---\nRead references/check.md.\n'
  const asset = Buffer.from([0, 255, 128, 13, 10])
  writeFileSync(join(source, 'SKILL.md'), instructions)
  writeFileSync(join(source, 'assets/sample.bin'), asset)
  writeFileSync(join(source, 'references/check.md'), 'Inspect the evidence.')
  const { directory } = await vista.api('/skills')
  mkdirSync(join(directory, 'keep'))
  mkdirSync(join(root, 'skills', 'keep'))
  const keep = '---\nname: Existing guide\ndescription: Preserve this\n---\nKeep original content'
  writeFileSync(join(directory, 'keep', 'SKILL.md'), keep)
  writeFileSync(join(root, 'skills', 'keep', 'SKILL.md'), keep.replace('original', 'source'))
  let reads = 0
  page.on('request', request => { if (request.url().endsWith('/api/extension-import')) reads++ })
  await page.goto(`${vista.origin}/settings/skills`)
  await page.getByRole('button', { name: 'Import skills', exact: true }).click()
  const modal = page.locator('.provider-import-modal')
  await expect(modal).toBeVisible()
  expect(reads).toBe(0)
  await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
  await expect(modal.getByRole('checkbox', { name: /^Existing guide/ })).toBeDisabled()
  await expect(modal.getByRole('checkbox', { name: /^Imported review/ })).toBeChecked()
  await expect(modal.getByText('3 files, including supporting files')).toBeVisible()
  expect(existsSync(join(directory, 'review-pack'))).toBe(false)
  writeFileSync(join(source, 'assets/sample.bin'), Buffer.from([1, 2, 3]))
  await modal.getByRole('button', { name: 'Import (1)', exact: true }).click()
  await expect(modal.locator('.ant-alert-error')).toContainText('OpenCode source changed')
  expect(existsSync(join(directory, 'review-pack'))).toBe(false)
  await modal.getByRole('button', { name: 'Read configuration', exact: true }).click()
  await modal.getByRole('button', { name: 'Import (1)', exact: true }).click()
  await expect(modal).toBeHidden()
  const card = page.locator('[data-skill="review-pack"]')
  await expect(card).toContainText('Imported review')
  expect(readFileSync(join(directory, 'review-pack', 'SKILL.md'), 'utf8')).toBe(instructions)
  expect(readFileSync(join(directory, 'review-pack', 'assets/sample.bin'))).toEqual(Buffer.from([1, 2, 3]))
  expect(readFileSync(join(directory, 'review-pack', 'references/check.md'), 'utf8')).toBe('Inspect the evidence.')
  expect(readFileSync(join(directory, 'keep', 'SKILL.md'), 'utf8')).toBe(keep)
  await page.screenshot({ path: testInfo.outputPath('skills-import.png'), animations: 'disabled' })
})
