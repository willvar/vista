  writeFileSync(join(folder, 'references/checklist.md'), 'Original reference.\n')
  writeFileSync(join(folder, 'assets/raw.bin'), Buffer.from([0, 255, 128]))
  writeFileSync(join(folder, 'assets/pixel.png'), Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aTWQAAAAASUVORK5CYII=', 'base64'))
  const reads: string[] = []
  page.on('request', request => { if (request.method() === 'GET' && request.url().includes('/api/skills/complete-pack')) reads.push(new URL(request.url()).search) })
