import { test, expect } from './fixtures'

test.describe('automatic recovery', () => {
  test.use({ modelFailure: { status: 400, body: { error: { code: 'context_length_exceeded', message: 'Context length exceeded' } }, attempts: 1, skipAttempts: 1 } })

  test('an automatic summary appears once between the input and continued answer', { tag: '@smoke' }, async ({ page, vista }) => {
    await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
    const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Preserve these verified findings. '.repeat(160) }) })
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
    await page.goto(`${vista.origin}/sessions/${session.id}`)
    const reads: string[] = []
    page.on('request', request => { if (request.method() === 'GET') reads.push(new URL(request.url()).pathname) })
    const draft = page.locator('.sender-card textarea')
    await expect(draft).toBeFocused()
    reads.length = 0
    await draft.fill('Continue with the findings')
    await draft.press('Enter')
    const summary = page.locator('article[data-context-summary]')
    await expect(summary).toHaveCount(1)
    await expect(summary.locator('.markdown')).toHaveText('Saved verified findings and constraints.')
    await expect(summary.getByRole('button', { name: 'Copy reply', exact: true })).toBeVisible()
    await expect(summary.locator('.reply-feedback, .reply-feedback-trigger')).toHaveCount(0)
    const knownModel = (await vista.api('/models')).models.find((model: any) => model.id === vista.modelId)
    await expect(summary.locator('.message-model-name')).toContainText(knownModel.modelName || vista.modelId)
    await expect(summary.locator('.token-usage')).toContainText('321')
    await expect(summary.locator('.model-call-count')).toHaveText('· 1 model call')
    await summary.locator('.model-call-count').click()
    await expect(page.locator('.usage-table tbody tr')).toHaveCount(1)
    await expect(page.locator('.usage-table tbody tr')).toContainText('321')
    await page.keyboard.press('Escape')
    await expect(page.locator('.context-status')).toHaveCount(0)
    await expect(page.locator('.context-notice')).toHaveCount(0)
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
    const messages = await vista.api(`/sessions/${session.id}/messages`)
    expect(messages.filter((item: any) => item.contextSummary)).toHaveLength(1)
    expect(messages.slice(-3).map((item: any) => [item.role, !!item.contextSummary])).toEqual([
      ['user', false], ['assistant', true], ['assistant', false],
    ])
    expect(reads).not.toContain(`/api/sessions/${session.id}/messages`)
    const lastInput = vista.modelRequests.at(-1)?.messages || []
    expect(lastInput.filter(item => item.role === 'assistant' && String(item.content).startsWith('Summary of completed execution'))).toHaveLength(1)
    expect(lastInput.some(item => item.content === 'Saved verified findings and constraints.')).toBe(false)
    await page.reload()
    await expect(summary).toHaveCount(1)
    await expect(summary.locator('.markdown')).toHaveText('Saved verified findings and constraints.')
    await expect(summary.locator('.model-call-count')).toHaveText('· 1 model call')
    await expect(summary.locator('.token-usage')).toContainText('321')
    await expect(page.locator('.context-status, .context-notice')).toHaveCount(0)
  })
})

test.describe('single completed reply', () => {
  test.use({ replyWithPrompt: true })

  test('manual compaction reduces context and the next request reuses it', async ({ page, vista }, testInfo) => {
    await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
    const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
    const prompt = `Preserve the verified result: ${'The build and tests passed. '.repeat(160)}`.trim()
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: prompt }) })
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
    const messages = await vista.api(`/sessions/${session.id}/messages`)
    expect(messages).toHaveLength(2)
    const before = await vista.api(`/sessions/${session.id}/context-usage`)
    await page.goto(`${vista.origin}/sessions/${session.id}`)
    await page.getByRole('button', { name: 'Compact context', exact: true }).click()
    await page.getByRole('dialog', { name: 'Compact this context?', exact: true }).getByRole('button', { name: 'Compact context', exact: true }).click()
    await expect.poll(async () => (await vista.api(`/sessions/${session.id}/context`))?.phase).toBe('compacted')
    const after = await vista.api(`/sessions/${session.id}/context-usage`)
    expect(after.tokens).toBeLessThan(before.tokens)
    const compactedMessages = await vista.api(`/sessions/${session.id}/messages`)
    expect(compactedMessages.filter((item: any) => !item.contextSummary)).toEqual(messages)
    const summaries = compactedMessages.filter((item: any) => item.contextSummary)
    expect(summaries).toHaveLength(1)
    const summary = page.locator('article[data-context-summary]')
    await expect(summary).toHaveCount(1)
    await expect(summary.locator('.markdown')).toHaveText(summaries[0].content)
    await expect(summary.getByRole('button', { name: 'Copy reply', exact: true })).toBeVisible()
    await expect(page.locator('.context-status')).toHaveCount(0)
    await expect(page.locator('.context-notice')).toHaveCount(0)
    await page.evaluate(() => localStorage.setItem('vista-language', 'zh-CN'))
    await page.reload()
    await expect(summary).toHaveCount(1)
    await expect(summary.locator('.markdown')).toHaveText(summaries[0].content)
    await expect(page.locator('.context-status')).toHaveCount(0)
    await expect(page.locator('.context-compaction')).toHaveAttribute('data-tokens', String(after.tokens))
    const draft = page.locator('.sender-card textarea')
    await expect(draft).toBeFocused()
    await expect(draft).toHaveAttribute('placeholder', '继续 · 点击此处后按 Tab 填入')
    await page.screenshot({ path: testInfo.outputPath('continue-completion-zh-CN.png'), animations: 'disabled' })
    const requests = vista.modelRequests.length
    await page.keyboard.press('Tab')
    await expect(draft).toHaveValue('继续')
    await expect(draft).toBeFocused()
    expect(vista.modelRequests.length).toBe(requests)
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await expect.poll(async () => vista.modelRequests.length).toBeGreaterThan(requests)
    const input = vista.modelRequests.at(-1)?.messages || []
    expect(input.some(item => item.role === 'user' && item.content === prompt)).toBe(true)
    expect(input.filter(item => item.role === 'assistant' && String(item.content).startsWith('Summary of completed execution'))).toHaveLength(1)
    expect(input.some(item => item.role === 'assistant' && item.content === summaries[0].content)).toBe(false)
    expect(input.some(item => item.content === `Mock reply: ${prompt}`)).toBe(false)
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
  })
})

test('manual compaction preserves chat and draft, and Tab completes Continue without sending or trapping focus', async ({ page, vista }, testInfo) => {
  // A preference left by the removed switch must not disable navigation or completion.
  await page.addInitScript(() => localStorage.setItem('vista-keyboard-navigation', 'off'))
  await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  for (let i = 0; i < 3; i++) {
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: `Request ${i}: ${'Retain the verified findings. '.repeat(100)}` }) })
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
  }
  const before = await vista.api(`/sessions/${session.id}/messages`)
  const beforeUsage = await vista.api(`/sessions/${session.id}/context-usage`)
  await page.goto(`${vista.origin}/sessions/${session.id}`)
  const compact = page.locator('.conversation-header .context-compaction')
  await expect(compact).toHaveAttribute('data-tokens', String(beforeUsage.tokens))
  // The usage estimate can arrive before history's initial scroll. Scrolling
  // dismisses tooltips, so wait for presentation rather than just header data.
  await expect(page.locator('.messages')).toHaveAttribute('aria-busy', 'false')
  await compact.hover()
  await expect(page.locator('.context-usage-hint:visible')).toContainText('Estimated tokens from retained instructions, messages, summaries and tool content:')
  await page.keyboard.press('Escape')
  const requestsBeforeConfirmation = vista.modelRequests.length
  await compact.click()
  const confirmation = page.getByRole('dialog', { name: 'Compact this context?', exact: true })
  await expect(confirmation).toContainText('Vista automatically compacts context')
  await expect(confirmation).toContainText('consuming tokens and potentially losing details')
  expect(vista.modelRequests.length).toBe(requestsBeforeConfirmation)
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(vista.modelRequests.length).toBe(requestsBeforeConfirmation)
  await compact.click()
  await page.keyboard.press('Escape')
  await expect(confirmation).toBeHidden()
  expect(vista.modelRequests.length).toBe(requestsBeforeConfirmation)
  await expect(page.locator('.message-meta small')).toHaveCount(0)
  const draft = page.locator('.sender-card textarea')
  await draft.fill('Keep my unsent draft')
  const release = vista.pauseModelReplies()
  try {
    await page.getByRole('button', { name: 'Compact context', exact: true }).click()
    await page.getByRole('dialog', { name: 'Compact this context?', exact: true }).getByRole('button', { name: 'Compact context', exact: true }).click()
    await expect(page.locator('.compaction-progress')).toContainText('Compacting context')
    await expect(draft).toHaveValue('Keep my unsent draft')
    await expect(draft).toHaveAttribute('placeholder', 'Send a message')
    await page.reload()
    await expect(page.locator('.compaction-progress')).toContainText('Compacting context')
    await expect(draft).toBeDisabled()
    await expect(draft).toHaveValue('Keep my unsent draft')
    await expect(page.locator('.conversation-header .context-status')).toHaveCount(0)
    await expect(page.locator('.sender-card .context-status')).toHaveCount(1)
    await expect(page.locator('.sender-state')).toHaveCount(0)
    for (const language of ['en', 'zh-CN']) {
      await page.evaluate(value => localStorage.setItem('vista-language', value), language)
      await page.reload()
      const progress = page.locator('.compaction-progress')
      await expect(progress).toContainText(language === 'en' ? 'Your chat history is kept.' : '保留聊天记录')
      await progress.getByRole('button', { name: language === 'en' ? 'Cancel' : '取消', exact: true }).click({ trial: true })
      const layout = await progress.evaluate(element => {
        const box = element.getBoundingClientRect()
        return { left: box.left, top: box.top, right: box.right, bottom: box.bottom, width: innerWidth, height: innerHeight, overflow: element.scrollWidth - element.clientWidth }
      })
      expect(layout.left).toBeGreaterThanOrEqual(0)
      expect(layout.top).toBeGreaterThanOrEqual(0)
      expect(layout.right).toBeLessThanOrEqual(layout.width)
      expect(layout.bottom).toBeLessThanOrEqual(layout.height)
      expect(layout.overflow).toBeLessThanOrEqual(2)
      await page.screenshot({ path: testInfo.outputPath(`compacting-${language}.png`), animations: 'disabled' })
    }
    await page.evaluate(() => localStorage.setItem('vista-language', 'en'))
    await page.reload()
    await expect(draft).toBeDisabled()
  } finally { release() }
  await expect.poll(async () => (await vista.api(`/sessions/${session.id}/context`))?.phase).toBe('compacted')
  const afterUsage = await vista.api(`/sessions/${session.id}/context-usage`)
  expect(afterUsage.tokens).toBeGreaterThan(0)
  expect(afterUsage.tokens).toBeLessThan(beforeUsage.tokens)
  await expect(draft).toBeEnabled()
  await expect(draft).toBeFocused()
  await expect(page.locator('.context-status')).toHaveCount(0)
  await expect(page.locator('article[data-context-summary]')).toHaveCount(1)
  await expect(page.locator('.context-notice')).toHaveCount(0)
  await expect(page.locator('.context-compaction')).toHaveAttribute('data-tokens', String(afterUsage.tokens))
  await expect(draft).toBeEnabled()
  const compactedMessages = await vista.api(`/sessions/${session.id}/messages`)
  expect(compactedMessages.filter((item: any) => !item.contextSummary)).toEqual(before)
  expect(compactedMessages.filter((item: any) => item.contextSummary)).toHaveLength(1)
  await page.reload()
  await expect(draft).toHaveValue('Keep my unsent draft')
  await expect(draft).toBeFocused()
  expect(await draft.evaluate((element: HTMLTextAreaElement) => element.selectionStart)).toBe('Keep my unsent draft'.length)
  await expect(page.locator('.context-status')).toHaveCount(0)
  await expect(page.locator('article[data-context-summary]')).toHaveCount(1)
  await expect(page.locator('.context-compaction')).toHaveAttribute('data-tokens', String(afterUsage.tokens))
  await draft.press('Tab')
  await expect(draft).toHaveValue('Keep my unsent draft')
  await expect(draft).not.toBeFocused()
  await draft.fill('')
  await expect(draft).toHaveAttribute('placeholder', 'Continue · click here, then press Tab to fill')
  await expect.poll(() => page.locator('.messages').evaluate(element => element.scrollHeight - element.clientHeight - element.scrollTop)).toBeLessThanOrEqual(3)
  const requests = vista.modelRequests.length
  await draft.press('Enter')
  await expect(draft).toHaveValue('')
  await draft.press('Shift+Tab')
  await expect(draft).toHaveValue('')
  await expect(draft).not.toBeFocused()
  await draft.focus()
  await draft.dispatchEvent('keydown', { key: 'Tab', code: 'Tab', isComposing: true })
  await draft.dispatchEvent('keydown', { key: 'Tab', code: 'Tab', repeat: true })
  await expect(draft).toHaveValue('')
  expect(vista.modelRequests.length).toBe(requests)
  await page.screenshot({ path: testInfo.outputPath('continue-completion-en.png'), animations: 'disabled' })
  await page.keyboard.press('Tab')
  await expect(draft).toHaveValue('Continue')
  await expect(draft).toBeFocused()
  expect(await draft.evaluate((element: HTMLTextAreaElement) => [element.selectionStart, element.selectionEnd])).toEqual([8, 8])
  expect(vista.modelRequests.length).toBe(requests)
  await expect(draft).toHaveAttribute('placeholder', 'Send a message')
  await page.keyboard.press('Tab')
  await expect(draft).not.toBeFocused()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect.poll(async () => vista.modelRequests.length).toBeGreaterThan(requests)
  expect(JSON.stringify(vista.modelRequests.at(-1)?.messages)).toContain('Summary of completed execution')
  await expect(draft).toHaveValue('')
  await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
  await page.reload()
  await expect(draft).toHaveAttribute('placeholder', 'Send a message')
  await draft.press('Tab')
  await expect(draft).toHaveValue('')
  await expect(draft).not.toBeFocused()
  const overflow = await page.locator('.sender-card').evaluate(element => {
    const box = element.getBoundingClientRect()
    return box.left < -1 || box.right > innerWidth + 1 || element.scrollWidth > element.clientWidth + 2
  })
  expect(overflow).toBe(false)
})

test('canceling manual compaction ends maintenance without inserting a reply or sending queued work', async ({ page, vista }) => {
  await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  for (let i = 0; i < 2; i++) {
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: `Request ${i}: ${'Fact. '.repeat(300)}` }) })
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
  }
  const before = await vista.api(`/sessions/${session.id}/messages`)
  await page.goto(`${vista.origin}/sessions/${session.id}`)
  const release = vista.pauseModelReplies()
  try {
    await page.getByRole('button', { name: 'Compact context', exact: true }).click()
    await page.getByRole('dialog', { name: 'Compact this context?', exact: true }).getByRole('button', { name: 'Compact context', exact: true }).click()
    await expect(page.locator('.compaction-progress')).toBeVisible()
    await page.locator('.compaction-progress').getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.locator('.compaction-progress')).toHaveCount(0)
    await expect(page.locator('.sender-card textarea')).toBeEnabled()
    await expect.poll(async () => (await vista.api(`/sessions/${session.id}/context`))?.phase).toBe('failed')
    expect(await vista.api(`/sessions/${session.id}/messages`)).toEqual(before)
    await expect(page.locator('.sender-card textarea')).toHaveAttribute('placeholder', 'Send a message')
    await page.reload()
    await page.locator('.context-status').click()
    await expect(page.locator('.context-status-detail')).toContainText('Compaction did not finish')
    await expect(page.locator('.context-status-detail').getByRole('button', { name: 'Analyze this failure in a new conversation', exact: true })).toBeVisible()
    await expect(page.locator('.context-status-detail')).toContainText('manual context compaction')
  } finally { release() }
})
