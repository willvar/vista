import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { test, expect } from './fixtures'

test.use({ replyWithPrompt: true, fileChanges: true })

test('edit and withdrawal roll back context while retaining file changes', async ({ page, vista }, testInfo) => {
  await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  const send = async (content: string) => {
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content }) })
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
  }
  await send('Keep this earlier question')
  await send('Edit files')
  const original = await vista.api(`/sessions/${session.id}/messages`)
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 1')
  await page.goto(`${vista.origin}/sessions/${session.id}`)
  const draft = page.locator('.sender-card textarea')
  await draft.fill('Existing unsent draft')
  const user = page.locator('article.user').filter({ hasText: 'Edit files' })
  await user.hover()
  await user.getByRole('button', { name: 'Edit message', exact: true }).click()
  await expect(draft).toHaveValue('Edit files')
  await expect(page.locator('.sender-editing')).toBeVisible()
  await expect(page.locator('.sender-editing')).toContainText('file changes are kept')
  expect(await vista.api(`/sessions/${session.id}/messages`)).toEqual(original)
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 1')
  await page.getByRole('button', { name: 'Cancel editing', exact: true }).click()
  await expect(draft).toHaveValue('Existing unsent draft')
  await user.hover()
  await user.getByRole('button', { name: 'Edit message', exact: true }).click()
  await draft.fill('Edit files v2')
  await draft.press('Enter')
  await expect(page.locator('article.assistant').last()).toContainText('Mock reply: Edit files v2')
  await expect(page.locator('.sender-editing')).toHaveCount(0)
  const edited = await vista.api(`/sessions/${session.id}/messages`)
  expect(edited).toHaveLength(4)
  expect(edited[2].content).toBe('Edit files v2')
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 2')
  await page.reload()
  const revised = page.locator('article.user').filter({ hasText: 'Edit files v2' })
  await revised.hover()
  await revised.getByRole('button', { name: 'Withdraw message', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Only the conversation is rolled back. File changes are kept.')
  await page.getByRole('dialog').getByRole('button', { name: 'Withdraw message', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(draft).toHaveValue('Edit files v2')
  await expect(page.locator('article')).toHaveCount(2)
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 2')
  expect(existsSync(join(vista.workspacePath, 'deleted.txt'))).toBe(false)
  expect(readFileSync(join(vista.workspacePath, 'added.txt'), 'utf8')).toBe('created')
  await draft.fill('Follow up after rollback')
  await draft.press('Enter')
  await expect(page.locator('article.assistant').last()).toContainText('Mock reply: Follow up after rollback')
  const input = vista.modelRequests.at(-1)?.messages || []
  expect(input.some(item => item.content === 'Keep this earlier question')).toBe(true)
  expect(input.some(item => String(item.content).includes('Edit files'))).toBe(false)
  expect(input.some(item => item.role === 'tool')).toBe(false)
  await page.screenshot({ path: testInfo.outputPath('message-revert.png'), animations: 'disabled' })
})

test('external file changes do not block conversation withdrawal', async ({ page, vista }) => {
  await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Edit files' }) })
  await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
  writeFileSync(join(vista.workspacePath, 'source.txt'), 'user changes')
  await page.goto(`${vista.origin}/sessions/${session.id}`)
  const user = page.locator('article.user')
  await user.hover()
  await user.getByRole('button', { name: 'Withdraw message', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Withdraw message', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect(await vista.api(`/sessions/${session.id}/messages`)).toEqual([])
  await expect(page.locator('.sender-card textarea')).toHaveValue('Edit files')
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('user changes')
  expect(readFileSync(join(vista.workspacePath, 'added.txt'), 'utf8')).toBe('created')
})

test('withdrawal during a live response stops execution and retains file changes', async ({ page, vista }) => {
  await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  const release = vista.pauseModelReplies(true)
  try {
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Edit files' }) })
    await page.goto(`${vista.origin}/sessions/${session.id}`)
    await expect(page.locator('article.assistant')).toContainText('Mock reply: Edit files')
    const user = page.locator('article.user')
    await user.hover()
    await user.getByRole('button', { name: 'Withdraw message', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Withdraw message', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 1')
    release()
    await expect.poll(async () => (await vista.api(`/sessions/${session.id}/messages`)).length).toBe(0)
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
    await expect(page.locator('.sender-card textarea')).toHaveValue('Edit files')
  } finally { release() }
})

test.describe('background and interjection boundaries', () => {
  test.use({ backgroundProcess: true })
  test('withdrawal stops a session-owned background process', async ({ page, vista }) => {
    await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
    const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Start process' }) })
    await expect.poll(async () => (await vista.api(`/sessions/${session.id}/jobs`))[0]?.status).toBe('running')
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
    await page.goto(`${vista.origin}/sessions/${session.id}`)
    const user = page.locator('article.user')
    await user.hover()
    await user.getByRole('button', { name: 'Withdraw message', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Withdraw message', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect(await vista.api(`/sessions/${session.id}/jobs`)).toEqual([])
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).running).toBe(false)
  })
})

test.describe('same-run interjection', () => {
  test.use({ followUpTool: true })
  test('withdrawing an interjection preserves the earlier reply and stays idle after reload', async ({ page, vista }) => {
    await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
    const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
    const release = vista.pauseModelReplies(true)
    try {
      await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'First question' }) })
      await page.goto(`${vista.origin}/sessions/${session.id}`)
      await expect(page.locator('article.assistant')).toContainText('Mock reply: First question')
      await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Follow-up question', mode: 'now' }) })
      release()
      await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
      const before = await vista.api(`/sessions/${session.id}/messages`)
      expect(before).toHaveLength(4)
      expect(before[0].runId).toBe(before[2].runId)
      await page.reload()
      const followup = page.locator('article.user').filter({ hasText: 'Follow-up question' })
      await followup.hover()
      await followup.getByRole('button', { name: 'Withdraw message', exact: true }).click()
      await page.getByRole('dialog').getByRole('button', { name: 'Withdraw message', exact: true }).click()
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await page.reload()
      await expect(page.locator('article')).toHaveCount(2)
      await expect(page.locator('article.assistant')).toContainText('Mock reply: First question')
      await expect(page.getByRole('button', { name: 'Stop current execution', exact: true })).toHaveCount(0)
      expect((await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
    } finally { release() }
  })
})
