import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { test, expect } from './fixtures'

test.use({ replyWithPrompt: true, fileChanges: true })

test('editing and withdrawal create independent branches and retain file changes', async ({ page, vista }, testInfo) => {
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  const send = async (content: string) => {
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content }) })
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
  }
  await send('Keep this earlier question')
  await send('Edit files')
  const original = await vista.api(`/sessions/${session.id}/messages`)
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 1')
  await page.goto(`${vista.origin}/sessions/${session.id}`)
  const draft = page.locator('.sender-card textarea')
  await draft.fill('Existing unsent draft')
  const user = page.locator('article.user').filter({ hasText: 'Edit files' })
  await user.hover()
  await user.getByRole('button', { name: 'Edit message', exact: true }).click()
  await expect(draft).toHaveValue('Edit files')
  await expect(page.locator('.sender-editing')).toBeVisible()
  await expect(page.locator('.sender-editing')).toContainText('file changes are kept')
  expect(await vista.api(`/sessions/${session.id}/messages`)).toEqual(original)
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 1')
  await page.getByRole('button', { name: 'Cancel editing', exact: true }).click()
  await expect(draft).toHaveValue('Existing unsent draft')
  await user.hover()
  await user.getByRole('button', { name: 'Edit message', exact: true }).click()
  await expect(page.locator('.sender-editing')).toBeVisible()
  await expect(draft).toHaveValue('Edit files')
  await draft.fill('Edit files v2')
  await expect(draft).toHaveValue('Edit files v2')
  await draft.press('Enter')
  await expect(page.locator('article.assistant').last()).toContainText('Mock reply: Edit files v2')
  await expect(page.locator('.sender-editing')).toHaveCount(0)
  const editedID=page.url().split('/').at(-1)
  expect(editedID).not.toBe(session.id)
  expect(await vista.api(`/sessions/${session.id}/messages`)).toEqual(original)
  expect(await vista.api('/sessions')).toHaveLength(1)
  const edited = await vista.api(`/sessions/${editedID}/messages`)
  expect(edited).toHaveLength(4)
  expect(edited[2].content).toBe('Edit files v2')
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 2')
  await page.reload()
  const revised = page.locator('article.user').filter({ hasText: 'Edit files v2' })
  await revised.hover()
  await revised.getByRole('button', { name: 'Withdraw message', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('File changes are kept.')
  await page.getByRole('dialog').getByRole('button', { name: 'Withdraw message', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(draft).toHaveValue('Edit files v2')
  await expect(page.locator('article')).toHaveCount(2)
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 2')
  expect(existsSync(join(vista.workspacePath, 'deleted.txt'))).toBe(false)
  expect(readFileSync(join(vista.workspacePath, 'added.txt'), 'utf8')).toBe('created')
  await draft.fill('Follow up after rollback')
  await draft.press('Enter')
  await expect(page.locator('article.assistant').last()).toContainText('Mock reply: Follow up after rollback')
  const input = vista.modelRequests.at(-1)?.messages || []
  expect(input.some(item => item.content === 'Keep this earlier question')).toBe(true)
  expect(input.some(item => String(item.content).includes('Edit files'))).toBe(false)
  expect(input.some(item => item.role === 'tool')).toBe(false)
  await page.screenshot({ path: testInfo.outputPath('message-revert.png'), animations: 'disabled' })
})

test('external file changes do not block conversation withdrawal', async ({ page, vista }) => {
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Edit files' }) })
  await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
  writeFileSync(join(vista.workspacePath, 'source.txt'), 'user changes')
  await page.goto(`${vista.origin}/sessions/${session.id}`)
  const user = page.locator('article.user')
  await user.hover()
  await user.getByRole('button', { name: 'Withdraw message', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Withdraw message', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const fork=page.url().split('/').at(-1)
  expect(fork).not.toBe(session.id)
  expect(await vista.api(`/sessions/${fork}/messages`)).toEqual([])
  expect(await vista.api(`/sessions/${session.id}/messages`)).toHaveLength(2)
  await expect(page.locator('.sender-card textarea')).toHaveValue('Edit files')
  expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('user changes')
  expect(readFileSync(join(vista.workspacePath, 'added.txt'), 'utf8')).toBe('created')
})

test('withdrawal during a live response preserves both branches and file changes', async ({ page, vista }) => {
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  const release = vista.pauseModelReplies(true)
  try {
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Edit files' }) })
    await page.goto(`${vista.origin}/sessions/${session.id}`)
    await expect(page.locator('article.assistant')).toContainText('Mock reply: Edit files')
    const user = page.locator('article.user')
    await user.hover()
    await user.getByRole('button', { name: 'Withdraw message', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Withdraw message', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect(readFileSync(join(vista.workspacePath, 'source.txt'), 'utf8')).toBe('agent version 1')
    release()
    const fork=page.url().split('/').at(-1)
    expect(fork).not.toBe(session.id)
    expect(await vista.api(`/sessions/${fork}/messages`)).toEqual([])
    await expect.poll(async () => (await vista.api(`/sessions/${session.id}/messages`)).length).toBe(2)
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
    await expect(page.locator('.sender-card textarea')).toHaveValue('Edit files')
  } finally { release() }
})

test.describe('background and interjection boundaries', () => {
  test.use({ backgroundProcess: true })
  test('withdrawal leaves a background process on its original branch', async ({ page, vista }) => {
    const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
    await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Start process' }) })
    await expect.poll(async () => (await vista.api(`/sessions/${session.id}/jobs`))[0]?.status).toBe('running')
    await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
    await page.goto(`${vista.origin}/sessions/${session.id}`)
    const user = page.locator('article.user')
    await user.hover()
    await user.getByRole('button', { name: 'Withdraw message', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Withdraw message', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    const fork=page.url().split('/').at(-1)
    expect(fork).not.toBe(session.id)
    expect(await vista.api(`/sessions/${fork}/jobs`)).toEqual([])
    expect((await vista.api(`/sessions/${session.id}/jobs`))[0]?.status).toBe('running')
  })
})

test.describe('same-run interjection', () => {
  test.use({ followUpTool: true })
  test('withdrawing an interjection preserves the earlier reply and stays idle after reload', async ({ page, vista }) => {
    const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
    const release = vista.pauseModelReplies(true)
    try {
      await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'First question' }) })
      await page.goto(`${vista.origin}/sessions/${session.id}`)
      await expect(page.locator('article.assistant')).toContainText('Mock reply: First question')
      await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Follow-up question', mode: 'now' }) })
      release()
      await expect.poll(async () => (await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
      const before = await vista.api(`/sessions/${session.id}/messages`)
      expect(before).toHaveLength(4)
      expect(before[0].runId).toBe(before[2].runId)
      await page.reload()
      const followup = page.locator('article.user').filter({ hasText: 'Follow-up question' })
      await followup.hover()
      await followup.getByRole('button', { name: 'Withdraw message', exact: true }).click()
      await page.getByRole('dialog').getByRole('button', { name: 'Withdraw message', exact: true }).click()
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await page.reload()
      await expect(page.locator('article')).toHaveCount(2)
      await expect(page.locator('article.assistant')).toContainText('Mock reply: First question')
      await expect(page.getByRole('button', { name: 'Stop current execution', exact: true })).toHaveCount(0)
      expect((await vista.api('/sessions')).find((item: any) => item.id === session.id).executing).toBe(false)
    } finally { release() }
  })
})


test('the fork toolbar switches to a withdrawn draft and back without adding a sidebar conversation', { tag: '@responsive' }, async ({ page, vista, isMobile }) => {
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  const sent = await vista.api(`/sessions/${session.id}/messages`, { method: 'POST', body: JSON.stringify({ content: 'Timeline fixture' }) })
  await expect.poll(async () => (await vista.api(`/sessions/${session.id}/checkpoint`)).session.executing).toBe(false)
  await page.goto(`${vista.origin}/sessions/${session.id}`)
  const original = page.locator('article.user').filter({ hasText: 'Timeline fixture' })
  const forward = original.getByRole('button', { name: 'Next branch', exact: true })
  const actions = original.locator('.message-actions:not(.branch-navigation)')
  const draft = page.locator('.sender-card textarea')
  await expect(original).toBeVisible()
  await expect(forward).toHaveCount(0)
  await draft.focus()
  await expect(actions).toHaveCSS('opacity', isMobile ? '1' : '0')
  if (!isMobile) {
    await original.hover()
    await expect(actions).toHaveCSS('opacity', '1')
    await page.mouse.move(1, 1)
    await expect(actions).toHaveCSS('opacity', '0')
  }
  const result = await vista.api(`/sessions/${session.id}/messages/${sent.message.id}/revert`, { method: 'POST' })
  await expect(forward).toBeVisible()
  await expect(actions).toHaveCSS('opacity', '1')
  const headerPicker = page.locator('.conversation-header').getByRole('button', { name: 'Conversation branches', exact: true })
  await expect(headerPicker).toHaveCount(0)
  await expect(original.getByRole('group', { name: 'Conversation branches' })).toContainText('1 / 2')
  await expect(original.getByRole('button', { name: 'Previous branch' })).toBeDisabled()
  await draft.fill('Draft on original')
  if (isMobile) await forward.tap()
  else await forward.click()
  await expect(page).toHaveURL(`${vista.origin}/sessions/${result.session.id}`)
  await expect(page.locator('article.user')).toHaveCount(0)
  const fallback = page.locator('.draft-branch-navigation')
  await expect(fallback).toContainText('2 / 2')
  await expect(headerPicker).toHaveCount(0)
  await draft.fill('Draft on the other branch')
  await fallback.getByRole('button', { name: 'Previous branch' }).click()
  await expect(page).toHaveURL(`${vista.origin}/sessions/${session.id}`)
  await expect(original).toBeVisible()
  await expect(draft).toHaveValue('Draft on original')
  await forward.click()
  await expect(draft).toHaveValue('Draft on the other branch')
  expect((await vista.api('/sessions')).map((item: { id: string }) => item.id)).toEqual([session.id])
  expect((await vista.api('/status')).sessions.total).toBe(1)
})

test('arrows on the replacement message navigate to the corresponding message, not the latest reply', { tag: '@responsive' }, async ({ page, vista }) => {
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  async function send(id: string, content: string) {
    const result = await vista.api(`/sessions/${id}/messages`, { method: 'POST', body: JSON.stringify({ content }) })
    await expect.poll(async () => (await vista.api(`/sessions/${id}/checkpoint`)).session.executing).toBe(false)
    return result.message.id
  }
  await send(session.id, 'Unchanged message above both versions')
  const original = await send(session.id, 'Original question at the fork')
  await send(session.id, Array.from({ length: 28 }, (_, index) => `Later paragraph ${index}`).join('\n\n'))
  const { session: fork } = await vista.api(`/sessions/${session.id}/messages/${original}/revert`, { method: 'POST' })
  await send(fork.id, 'Changed question at the fork')
  await page.goto(`${vista.origin}/sessions/${fork.id}`)
  const revised = page.locator('article.user').filter({ hasText: 'Changed question at the fork' })
  await expect(page.locator('article.user').filter({ hasText: 'Unchanged message' }).getByRole('group', { name: 'Conversation branches' })).toHaveCount(0)
  await revised.getByRole('button', { name: 'Previous branch' }).click()
  await expect(page).toHaveURL(`${vista.origin}/sessions/${session.id}`)
  const forward = page.locator('article.user').filter({ hasText: 'Original question at the fork' }).getByRole('button', { name: 'Next branch' })
  await expect(forward).toBeInViewport()
  await forward.click()
  await expect(page).toHaveURL(`${vista.origin}/sessions/${fork.id}`)
  await expect(revised.getByRole('button', { name: 'Previous branch' })).toBeInViewport()
})
