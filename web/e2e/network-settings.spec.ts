  test('a delayed global save uses the latest synchronized configuration', async ({ page, vista }) => {
    const initial: NetworkConfiguration = await vista.api('/network-config')
    const profiles = ['p', 'q'].map(id => ({ id, name: `Proxy ${id.toUpperCase()}`, protocol: 'http', server: 'proxy.example', port: 3128, authentication: 'none' }))
    await vista.api('/network-config', { method: 'PUT', body: JSON.stringify({ config: { ...initial.config, profiles }, revision: initial.revision }) })
    await page.goto(vista.origin + '/settings/network')
    const global = page.locator('#network-global')
    const proxy = global.getByRole('combobox', { name: /^Network proxy/ })
    await choose(page, proxy, 'Proxy P')
    let release!: () => void, written!: (value: NetworkConfiguration) => void
    const held = new Promise<void>(resolve => { release = resolve })
    const responseReady = new Promise<NetworkConfiguration>(resolve => { written = resolve })
    await page.route('**/api/network-config', async route => {
      if (route.request().method() !== 'PUT') return route.continue()
      const response = await route.fetch()
      expect(response.ok()).toBe(true)
      written(await response.json())
      await held
      await route.fulfill({ response })
    })
    try {
      await global.getByRole('button', { name: 'Save changes', exact: true }).click()
      const saved = await responseReady
      const config = { ...saved.config, globalProxy: 'q', profiles: profiles.map(profile => profile.id === 'q' ? { ...profile, name: 'Proxy Q updated' } : profile) }
      await vista.api('/network-config', { method: 'PUT', body: JSON.stringify({ config, revision: saved.revision }) })
      await expect(page.locator('.network-profile')).toContainText(['Proxy P', 'Proxy Q updated'])
      release()
      await expect(global.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
      await expect(proxy).toHaveValue('Proxy Q updated')
    } finally { release() }
  })

