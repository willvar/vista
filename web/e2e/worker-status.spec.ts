import { test, expect } from './fixtures'
import type { CompactionStatus } from '../src/client/types'

test('worker metrics stay behind an icon and their popup fits the viewport', async ({ page, vista }, testInfo) => {
  await page.addInitScript(() => localStorage.setItem('vista-debug-mode', 'true'))
  await vista.api('/preferences', { method: 'PATCH', body: JSON.stringify({ feedbackInvitationSeen: true }) })
  const session = await vista.api('/sessions', { method: 'POST', body: '{}' })
  const catalog = await vista.api('/models')
  const budget: CompactionStatus = { runId: 'mock-compaction', manual: false, phase: 'compacted', sequence: 1 }
  await page.route('**/api/sessions/*/context', route => route.fulfill({ json: budget }))
  await page.goto(`${vista.origin}/sessions/${session.id}`)
  const header = page.locator('.workspace:not(.modal-page) > .conversation-header')
  const sender = page.locator('.sender-card')
  const worker = header.locator('.worker-status-trigger')
  const context = sender.locator('.context-status')
  const popup = page.locator('.worker-metrics-detail:visible')
  const contextPopup = page.locator('.context-status-detail:visible')
  await expect(worker).toBeVisible()
  await expect(worker.locator('svg.worker-memory-icon')).toBeVisible()
  await expect(worker).toHaveText('')
  await expect(worker).toHaveAttribute('aria-expanded', 'false')
  await expect(worker).toHaveAttribute('title', /Worker heap .*RSS .*sampled /)
  await expect(popup).toHaveCount(0)
  await expect(context).toHaveAttribute('aria-expanded', 'false')
  await expect(header.locator('.context-status')).toHaveCount(0)
  await expect(contextPopup).toHaveCount(0)
  await expect(header.locator('.worker-metrics')).toHaveCount(0)
  await expect(page.locator('.workspace > small')).toHaveCount(0)
  await expect(sender.locator('textarea')).toBeVisible()
  const geometry = await header.locator('.conversation-header-tools').evaluate(element => {
    const worker = element.querySelector('.worker-status-trigger')!.getBoundingClientRect()
    const bounds = element.getBoundingClientRect()
    return { workerWidth: worker.width, workerHeight: worker.height, left: bounds.left, right: bounds.right, top: bounds.top, bottom: bounds.bottom, viewportWidth: innerWidth, viewportHeight: innerHeight }
  })
  expect(geometry.workerWidth).toBeGreaterThanOrEqual(32)
  expect(geometry.workerHeight).toBeGreaterThanOrEqual(32)
  expect(geometry.left).toBeGreaterThanOrEqual(-1)
  expect(geometry.top).toBeGreaterThanOrEqual(-1)
  expect(geometry.right).toBeLessThanOrEqual(geometry.viewportWidth + 1)
  expect(geometry.bottom).toBeLessThanOrEqual(geometry.viewportHeight + 1)
  // Wait for initial font loading, textarea autosizing and entrance transitions
  // before attributing any later geometry change to opening a popup.
  await page.evaluate(() => document.fonts.ready.then(() => undefined))
  await page.waitForTimeout(350)
  const headerBefore = await header.boundingBox()
  const senderBefore = await sender.boundingBox()
  await page.screenshot({ path: testInfo.outputPath('worker-status-collapsed.png'), animations: 'disabled' })

  await worker.click()
  await expect(worker).toHaveAttribute('aria-expanded', 'true')
  await expect(popup).toContainText('Worker heap')
  await expect(popup).toContainText('RSS')
  await expect(popup).toContainText('Sampled')
  const popupGeometry = await popup.evaluate(element => {
    const bounds = element.getBoundingClientRect()
    return { left: bounds.left, right: bounds.right, top: bounds.top, bottom: bounds.bottom, width: innerWidth, height: innerHeight, overflow: element.scrollWidth - element.clientWidth }
  })
  expect(popupGeometry.left).toBeGreaterThanOrEqual(-1)
  expect(popupGeometry.top).toBeGreaterThanOrEqual(-1)
  expect(popupGeometry.right).toBeLessThanOrEqual(popupGeometry.width + 1)
  expect(popupGeometry.bottom).toBeLessThanOrEqual(popupGeometry.height + 1)
  expect(popupGeometry.overflow).toBeLessThanOrEqual(2)
  expect(await header.boundingBox()).toEqual(headerBefore)
  expect(await sender.boundingBox()).toEqual(senderBefore)
  await page.screenshot({ path: testInfo.outputPath('worker-status-open.png'), animations: 'disabled' })
  await context.click()
  await expect(popup).toHaveCount(0)
  await expect(worker).toHaveAttribute('aria-expanded', 'false')
  await expect(context).toHaveAttribute('aria-expanded', 'true')
  await expect(contextPopup).toContainText('Context saved. The task continues automatically.')
  await expect(context.locator('.ant-progress')).toHaveCount(0)
  const contextGeometry = await contextPopup.evaluate(element => {
    const bounds = element.getBoundingClientRect()
    return { left: bounds.left, right: bounds.right, top: bounds.top, bottom: bounds.bottom, width: innerWidth, height: innerHeight, overflow: element.scrollWidth - element.clientWidth, teleported: !element.closest('.conversation-header') }
  })
  expect(contextGeometry.teleported).toBe(true)
  expect(contextGeometry.left).toBeGreaterThanOrEqual(-1)
  expect(contextGeometry.top).toBeGreaterThanOrEqual(-1)
  expect(contextGeometry.right).toBeLessThanOrEqual(contextGeometry.width + 1)
  expect(contextGeometry.bottom).toBeLessThanOrEqual(contextGeometry.height + 1)
  expect(contextGeometry.overflow).toBeLessThanOrEqual(2)
  expect(await header.boundingBox()).toEqual(headerBefore)
  expect(await sender.boundingBox()).toEqual(senderBefore)
  await page.screenshot({ path: testInfo.outputPath('context-status-open.png'), animations: 'disabled' })
  await contextPopup.getByText('Context saved. The task continues automatically.', { exact: true }).click()
  await expect(contextPopup).toBeVisible()
  await worker.click()
  await expect(contextPopup).toHaveCount(0)
  await expect(context).toHaveAttribute('aria-expanded', 'false')
  await expect(popup).toBeVisible()
  await sender.locator('textarea').click()
  await expect(popup).toHaveCount(0)
  await expect(worker).toHaveAttribute('aria-expanded', 'false')
  await expect(sender.locator('textarea')).toBeFocused()
  await worker.click()
  await expect(popup).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(popup).toHaveCount(0)
  await expect(worker).toHaveAttribute('aria-expanded', 'false')
  expect(await header.boundingBox()).toEqual(headerBefore)
  expect(await sender.boundingBox()).toEqual(senderBefore)

  await context.click()
  await expect(contextPopup).toBeVisible()
  await sender.locator('textarea').click()
  await expect(contextPopup).toHaveCount(0)
  await expect(context).toHaveAttribute('aria-expanded', 'false')
  await expect(sender.locator('textarea')).toBeFocused()
  await context.click()
  await expect(contextPopup).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(contextPopup).toHaveCount(0)
  await expect(context).toHaveAttribute('aria-expanded', 'false')

})
