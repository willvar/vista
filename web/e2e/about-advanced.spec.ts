test('About lists the client runtime separately from the host OS @responsive', async ({ page, vista }) => {
  await page.goto(vista.origin + '/settings/about')
  const info = page.locator('.about-build-info')
  const runtime = info.locator('dt:text-is("Runtime environment") + dd')
  await expect(runtime).toHaveText('Browser')
  await expect(info.locator('dt:text-is("Host OS") + dd + dt')).toHaveText('Runtime environment')
  const hostOS = info.locator('dt:text-is("Host OS") + dd')
  const serverOS = await hostOS.innerText()

  // Direct About navigation may render before the desktop runtime is ready.
  await page.evaluate(() => {
    Object.assign(window, { _wails: { environment: { OS: 'windows' } } })
    window.dispatchEvent(new Event('wails:runtime-config-ready'))
  })
  await expect(runtime).toHaveText('Desktop app · Wails · WebView2')
  await page.evaluate(() => {
    Object.assign(window, { _wails: {
      environment: { OS: 'linux' },
      flags: { vistaWailsVersion: '3.1.0', vistaWebViewVersion: '2.54.2' },
    } })
    window.dispatchEvent(new Event('wails:runtime-config-ready'))
  })
  await expect(runtime).toHaveText('Desktop app · Wails 3.1.0 · WebKitGTK 2.54.2')
  await expect(hostOS).toHaveText(serverOS)
})

test('About keeps Restart unless a native tray controls this origin @responsive', async ({ page, vista }) => {
  await page.goto(vista.origin + '/settings/about')
  const restart = page.locator('.restart-vista-setting').getByRole('button', { name: 'Restart Vista', exact: true })
  const runtime = page.locator('.about-build-info dt:text-is("Runtime environment") + dd')
  const client = (os: string, origin?: string) => page.evaluate(({ os, origin }) => {
    Object.assign(window, { _wails: { environment: { OS: os }, flags: { vistaRestartTrayOrigin: origin } } })
    window.dispatchEvent(new Event('wails:runtime-config-ready'))
  }, { os, origin })

  await expect(restart).toBeVisible()
  await client('windows')
  await expect(runtime).toHaveText('Desktop app · Wails · WebView2')
  await expect(restart).toBeVisible()
  await client('windows', 'http://127.0.0.1:1')
  await expect(restart).toBeVisible()
  await client('windows', vista.origin)
  await expect(restart).toHaveCount(0)
  await client('windows')
  await expect(restart).toBeVisible()

  await restart.click()
  const confirmation = page.locator('.restart-vista-modal')
  await expect(confirmation).toBeVisible()
  await client('windows', vista.origin)
  await expect(confirmation).toBeVisible()
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(restart).toHaveCount(0)

  await client('linux', vista.origin)
  await expect(runtime).toHaveText('Desktop app · Wails · WebKitGTK')
  await expect(restart).toHaveCount(0)
  await client('linux')
  await expect(restart).toBeVisible()
  await client('darwin', vista.origin)
  await expect(runtime).toHaveText('Desktop app · Wails · WKWebView')
  await expect(restart).toHaveCount(0)
  await client('darwin')
  await expect(restart).toBeVisible()
})

const footer = (page: import('@playwright/test').Page) => page.locator('.about-advanced-modal .ui-modal-footer')

test('advanced tabs retain shared drafts and one save applies all tabs @responsive', async ({ page, vista }, testInfo) => {
  const reads: string[] = [], writes: string[] = []
  page.on('request', request => {
    const path = new URL(request.url()).pathname
    if (!/^\/api\/(user-agent|server-config|memory-config)$/.test(path)) return
    if (request.method() === 'GET') reads.push(path)
    if (request.method() === 'PUT') writes.push(path)
  })
  await page.goto(vista.origin + '/settings/about')
  expect(reads).toEqual([])
  const dialog = await openAboutAdvanced(page)
  const save = footer(page).getByRole('button', { name: 'Save changes', exact: true })
  await expect(dialog.getByRole('tab')).toHaveCount(4)
  const nav = dialog.getByRole('tablist', { name: 'Advanced settings', exact: true })
  await expect(nav).toHaveAttribute('aria-orientation', 'vertical')
  const tabs = await dialog.getByRole('tab').all()
  const positions = await Promise.all(tabs.map(tab => tab.boundingBox()))
  for (let i = 1; i < positions.length; i++) {
    expect(Math.abs(positions[i]!.x - positions[0]!.x)).toBeLessThanOrEqual(1)
    expect(positions[i]!.y).toBeGreaterThanOrEqual(positions[i - 1]!.y + positions[i - 1]!.height)
  }
  const panel = dialog.getByRole('tabpanel', { name: 'User-Agent', exact: true })
  expect((await panel.boundingBox())!.x).toBeGreaterThan((await nav.boundingBox())!.x + (await nav.boundingBox())!.width)
  await tabs[0]!.press('ArrowDown')
  await expect(tabs[1]!).toBeFocused()
  await expect(tabs[1]!).toHaveAttribute('aria-selected', 'true')
  await tabs[1]!.press('ArrowUp')
  await expect(tabs[0]!).toBeFocused()
  await expect(tabs[0]!).toHaveAttribute('aria-selected', 'true')
  await expect(save).toBeDisabled()
  await expect.poll(() => [...reads].sort()).toEqual(['/api/server-config', '/api/user-agent'])
  await dialog.getByRole('combobox', { name: 'Preset', exact: true }).click()
  await page.getByRole('option', { name: 'Custom', exact: true }).click()
  await dialog.getByRole('textbox', { name: 'Custom UA', exact: true }).fill('TabbedClient/1')
  const bounds: number[] = []
  for (const label of ['Memory and capacity', 'Service configuration', 'Debug mode', 'User-Agent']) {
    await dialog.getByRole('tab', { name: label, exact: true }).click()
    await expect(dialog.getByRole('tab', { name: label, exact: true })).toHaveAttribute('aria-selected', 'true')
    bounds.push((await dialog.boundingBox())!.height)
    const button = await save.boundingBox()
    expect(button!.y).toBeGreaterThanOrEqual(0)
    expect(button!.y + button!.height).toBeLessThanOrEqual(testInfo.project.use.viewport!.height)
    if (label === 'Memory and capacity') {
      await dialog.getByRole('combobox', { name: 'Capacity preset', exact: true }).click()
      await page.getByRole('option', { name: '1 GiB', exact: true }).click()
    } else if (label === 'Debug mode') await dialog.getByRole('switch', { name: 'Debug mode', exact: true }).check()
  }
  expect(Math.max(...bounds) - Math.min(...bounds)).toBeLessThanOrEqual(1)
  await expect(dialog.getByRole('textbox', { name: 'Custom UA', exact: true })).toHaveValue('TabbedClient/1')
  expect(writes).toEqual([])
  expect((await vista.api('/user-agent')).preset).toBe('vista')
  expect((await vista.api('/memory-config')).budgetMiB).toBe(2048)
  expect(await page.evaluate(() => localStorage.getItem('vista-debug-mode'))).toBeNull()
  await dialog.getByRole('tab', { name: 'Debug mode', exact: true }).click()
  await save.click()
  await expect(save).not.toHaveAttribute('aria-busy', 'true')
  await expect(save).toBeDisabled()
  await expect.poll(async () => (await vista.api('/user-agent')).value).toBe('TabbedClient/1')
  expect((await vista.api('/memory-config')).budgetMiB).toBe(1024)
  expect(await page.evaluate(() => localStorage.getItem('vista-debug-mode'))).toBe('true')
  expect(writes).toEqual(['/api/user-agent', '/api/memory-config'])
  expect([...reads].sort()).toEqual(['/api/server-config', '/api/user-agent'])
  await dialog.getByRole('tab', { name: 'Memory and capacity', exact: true }).click()
  await expect(dialog.getByRole('spinbutton', { name: 'Memory budget (MiB)', exact: true })).toHaveValue('1024')
  const memoryPanel = dialog.getByRole('tabpanel', { name: 'Memory and capacity', exact: true })
  expect(await memoryPanel.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await memoryPanel.evaluate(element => { element.scrollTop = element.scrollHeight })
  await expect(nav).toBeInViewport()
  await expect(save).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(testInfo.project.use.viewport!.width + 2)
  await page.screenshot({ path: testInfo.outputPath('advanced-tabs.png'), animations: 'disabled' })
})

test('invalid drafts lock other tabs and dismissal confirms discarding all tabs @responsive', async ({ page, vista }) => {
  const writes: string[] = []
  page.on('request', request => {
    if (request.method() === 'PUT' && /^\/api\/(user-agent|memory-config|server-config)$/.test(new URL(request.url()).pathname)) writes.push(request.url())
  })
  await page.goto(vista.origin + '/settings/about')
  const dialog = await openAboutAdvanced(page)
  await dialog.getByRole('combobox', { name: 'Preset', exact: true }).click()
  await page.getByRole('option', { name: 'Custom', exact: true }).click()
  const input = dialog.getByRole('textbox', { name: 'Custom UA', exact: true })
  await input.fill('无效的 UA')
  for (const label of ['Memory and capacity', 'Service configuration', 'Debug mode']) {
    const other = dialog.getByRole('tab', { name: label, exact: true })
    await expect(other).toBeDisabled()
    await expect(other).toHaveCSS('cursor', 'not-allowed')
    await other.click({ force: true })
  }
  const current = dialog.getByRole('tab', { name: 'User-Agent', exact: true })
  await current.focus()
  await current.press('ArrowDown')
  await expect(current).toHaveAttribute('aria-selected', 'true')
  await footer(page).getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(dialog.getByRole('tab', { name: 'User-Agent', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(input).toBeFocused()
  expect(writes).toEqual([])
  expect(await page.evaluate(() => localStorage.getItem('vista-debug-mode'))).toBeNull()
  await input.fill('KeptDraft/1')
  const debugTab = dialog.getByRole('tab', { name: 'Debug mode', exact: true })
  await expect(debugTab).toBeEnabled()
  await debugTab.click()
  await dialog.getByRole('switch', { name: 'Debug mode', exact: true }).check()
  await current.click()
  await page.keyboard.press('Escape')
  const discard = page.getByRole('dialog', { name: 'Discard unsaved changes', exact: true })
  await expect(discard).toBeVisible()
  await discard.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(discard).toBeHidden()
  await expect(input).toHaveValue('KeptDraft/1')
  await page.locator('.ui-modal-wrap').filter({ has: dialog }).click({ position: { x: 5, y: 5 } })
  await expect(discard).toBeVisible()
  await discard.getByRole('button', { name: 'Discard unsaved changes', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await openAboutAdvanced(page, 'Debug mode')
  await expect(dialog.getByRole('switch', { name: 'Debug mode', exact: true })).not.toBeChecked()
  expect(writes).toEqual([])
})

test('port confirmation precedes every tab save and port changes are sent last', async ({ page, vista }) => {
  const writes: string[] = []
  page.on('request', request => {
    const path = new URL(request.url()).pathname
    if (request.method() === 'PUT' && /^\/api\/(user-agent|memory-config|server-config)$/.test(path)) writes.push(path)
  })
  await page.route('**/api/server-config', async route => {
    if (route.request().method() !== 'PUT') return route.continue()
    expect((await vista.api('/user-agent')).value).toBe('BeforeRestart/1')
    expect((await vista.api('/memory-config')).budgetMiB).toBe(1024)
    expect(await page.evaluate(() => localStorage.getItem('vista-debug-mode'))).toBe('true')
    await route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ code: 'port_unavailable', error: 'Port unavailable' }) })
  })
  await page.goto(vista.origin + '/settings/about')
  const dialog = await openAboutAdvanced(page)
  await dialog.getByRole('combobox', { name: 'Preset', exact: true }).click()
  await page.getByRole('option', { name: 'Custom', exact: true }).click()
  await dialog.getByRole('textbox', { name: 'Custom UA', exact: true }).fill('BeforeRestart/1')
  await dialog.getByRole('tab', { name: 'Memory and capacity', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Capacity preset', exact: true }).click()
  await page.getByRole('option', { name: '1 GiB', exact: true }).click()
  await dialog.getByRole('tab', { name: 'Service configuration', exact: true }).click()
  const port = dialog.getByRole('spinbutton', { name: 'Listening port', exact: true })
  const next = String(Number(await port.inputValue()) === 65535 ? 65534 : Number(await port.inputValue()) + 1)
  await port.fill(next)
  await dialog.getByRole('tab', { name: 'Debug mode', exact: true }).click()
  await dialog.getByRole('switch', { name: 'Debug mode', exact: true }).check()
  const save = footer(page).getByRole('button', { name: 'Save changes', exact: true })
  await save.click()
  const confirmation = page.getByRole('dialog', { name: 'Save and restart', exact: true })
  await expect(confirmation).toBeVisible()
  expect(writes).toEqual([])
  expect(await page.evaluate(() => localStorage.getItem('vista-debug-mode'))).toBeNull()
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(writes).toEqual([])
  await save.click()
  await confirmation.getByRole('button', { name: 'Save and restart', exact: true }).click()
  await expect(dialog.getByRole('tab', { name: 'Service configuration', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(port).toHaveValue(next)
  await expect(dialog.getByRole('alert')).toContainText('cannot be reserved')
  expect(writes).toEqual(['/api/user-agent', '/api/memory-config', '/api/server-config'])
})
