package main

import (
	"bytes"
	"os"
	"testing"
)

func TestProviderMatrixFixtureMatchesOMPRoutes(t *testing.T) {
	var generated bytes.Buffer
	if err := writeMatrix(&generated); err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile("testdata/catalog.csv")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(generated.Bytes(), committed) {
		t.Fatal("provider route fixture is stale; regenerate it from the OMP inventory")
	}
}
