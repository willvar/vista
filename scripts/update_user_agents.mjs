import { randomUUID } from 'node:crypto'
import { readFile, rename, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

export const sources = [
  { constant: 'CodexVersion', package: '@openai/codex' },
  { constant: 'OpenCodeVersion', package: 'opencode-ai' },
  { constant: 'OhMyPiVersion', package: '@oh-my-pi/pi-coding-agent' },
  { constant: 'ClaudeCodeVersion', package: '@anthropic-ai/claude-code' },
  { constant: 'GeminiCLIVersion', package: '@google/gemini-cli' },
  { constant: 'KimiCodeVersion', package: '@moonshot-ai/kimi-code' },
  // The published CLI is `cline`; @cline/cli is an older, separate package.
  { constant: 'ClineVersion', package: 'cline' },
  { constant: 'CopilotVersion', package: '@github/copilot' },
]

const outputFile = fileURLToPath(new URL('../internal/useragent/versions_generated.go', import.meta.url))
const stableVersion = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/

export async function updateVersions({ output = outputFile, check = false, fetchImpl = fetch } = {}) {
  const current = await readFile(output, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return ''
    throw error
  })
  const results = await Promise.allSettled(sources.map(async source => {
    const response = await fetchImpl(`https://registry.npmjs.org/${encodeURIComponent(source.package)}/latest`, {
      headers: { Accept: 'application/json', 'User-Agent': 'vista-ua-updater' },
      signal: AbortSignal.timeout(15_000),
    })
    if (!response.ok) throw new Error(`HTTP ${response.status}`)
    const metadata = await response.json()
    if (metadata?.name !== source.package || typeof metadata.version !== 'string' || !stableVersion.test(metadata.version)) {
      throw new Error('expected matching package metadata with a stable major.minor.patch version')
    }
    const previous = current.match(new RegExp(`const ${source.constant} = "([^"]+)"`))?.[1]
    if (previous && stableVersion.test(previous)) {
      const next = metadata.version.split('.').map(BigInt)
      const before = previous.split('.').map(BigInt)
      const difference = next.map((part, index) => part - before[index]).find(part => part !== 0n)
      if (difference !== undefined && difference < 0n) throw new Error(`refusing downgrade from ${previous} to ${metadata.version}`)
    }
    return metadata.version
  }))
  const failures = results.flatMap((result, index) => result.status === 'rejected'
    ? [`${sources[index].package}: ${result.reason.message}`] : [])
  if (failures.length) throw new Error(`UA versions were not updated:\n${failures.join('\n')}`)

  const versions = results.map(result => result.value)
  const content = '// Code generated by node scripts/update_user_agents.mjs; DO NOT EDIT.\n\npackage useragent\n\n'
    + sources.map((source, index) => `// ${source.constant} tracks ${source.package}@latest.\nconst ${source.constant} = "${versions[index]}"\n`).join('\n')
  if (content === current) return { changed: false, versions }
  if (check) throw new Error('Bundled UA versions are stale. Run make update-ua.')

  const temporary = `${output}.${randomUUID()}.tmp`
  try {
    await writeFile(temporary, content, { flag: 'wx' })
    await rename(temporary, output)
  } finally {
    await rm(temporary, { force: true })
  }
  return { changed: true, versions }
}

if (import.meta.main) {
  try {
    if (process.argv.slice(2).some(argument => argument !== '--check')) {
      throw new Error('Usage: node scripts/update_user_agents.mjs [--check]')
    }
    const result = await updateVersions({ check: process.argv.includes('--check') })
    for (const [index, source] of sources.entries()) console.log(`${source.package}: ${result.versions[index]}`)
    console.log(`UA versions ${result.changed ? 'updated' : 'already current'}.`)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
